def flip_walk(df, rng):
    lo, lh, ll, lc = (np.log(df[c].to_numpy()) for c in ("open", "high", "low", "close"))
    prev = np.r_[lo[0], lc[:-1]]
    a = np.column_stack([lo - prev, lh - prev, ll - prev, lc - prev])
    s = rng.choice([-1.0, 1.0], len(df))
    o = np.where(s > 0, a[:, 0], -a[:, 0])
    h = np.where(s > 0, a[:, 1], -a[:, 2])
    l_ = np.where(s > 0, a[:, 2], -a[:, 1])
    c = np.where(s > 0, a[:, 3], -a[:, 3])
    base = np.log(df.close.iloc[0]) + np.r_[0, np.cumsum(c)[:-1]]
    return pd.DataFrame({"time": df.time, "open": np.exp(base + o), "high": np.exp(base + h),
                         "low": np.exp(base + l_), "close": np.exp(base + c)})


def garch_walk(df, rng, sub=8, nu=5.0, alpha=0.06, beta=0.92):
    r = np.diff(np.log(df.close.to_numpy()))
    var = np.var(r)
    n = len(df)
    omega = var * (1 - alpha - beta)
    h, x, out = var, 0.0, np.empty((n, 4))
    eps = student.rvs(nu, size=(n, sub), random_state=rng) * np.sqrt((nu - 2) / nu)
    p0 = np.log(df.close.iloc[0])
    for i in range(n):
        steps = np.cumsum(eps[i] * np.sqrt(h / sub))
        out[i] = (p0, p0 + max(0, steps.max()), p0 + min(0, steps.min()), p0 + steps[-1])
        ret = steps[-1]
        p0 = p0 + ret
        h = omega + alpha * ret * ret + beta * h
    return pd.DataFrame({"time": df.time, "open": np.exp(out[:, 0]), "high": np.exp(out[:, 1]),
                         "low": np.exp(out[:, 2]), "close": np.exp(out[:, 3])})


def aggregate(df, tf_from, tf_to):
    """Higher-timeframe bars from lower ones; only complete higher bars are kept."""
    span = MIN[tf_to] * 60
    g = (df.time // span) * span
    need = MIN[tf_to] // MIN[tf_from]
    a = df.groupby(g).agg(open=("open", "first"), high=("high", "max"), low=("low", "min"),
                          close=("close", "last"), n=("close", "size"), last=("time", "last"))
    # complete: its last lower bar is the final slot of the span (FX weekends end early, so
    # accept any bar whose next lower bar starts a new span)
    a = a.iloc[:-1] if len(a) else a
    a = a[a.n >= max(1, need // 3)]
    return a.reset_index().rename(columns={"time": "time"})[["time", "open", "high", "low", "close", "last"]]


def observations(df, obs="close", train_end=None):
    """Per bar: r (log close return), s (EWMA sigma known before the bar), and Y (n, D).

    close  Y = [y],                    y = r / s
    ohlc   Y = [y, location, range]:   location = (close - mid) / (high - low), in [-0.5, 0.5],
           where the close sits in its own bar; range = log((high - low) / prev close / s).
           The two candle columns are standardised by their training mean and sd.
    """
    c = df.close.to_numpy()
    h, l_ = df.high.to_numpy(), df.low.to_numpy()
    r = np.diff(np.log(c), prepend=np.nan)
    var = pd.Series(r ** 2).ewm(alpha=0.06, min_periods=50).mean().shift(1).to_numpy()
    s = np.sqrt(var)
    y = np.clip(r / s, -10, 10)
    if obs == "close":
        return r, s, y[:, None]
    rng_ = h - l_
    loc = np.where(rng_ > 0, (c - 0.5 * (h + l_)) / np.where(rng_ > 0, rng_, 1), 0.0)
    prev = np.r_[np.nan, c[:-1]]
    lr = np.log(np.maximum(rng_ / prev, 0.05 * s) / s)
    Y = np.column_stack([y, loc, lr])
    te = train_end or len(Y)
    for d in (1, 2):
        col = Y[:te, d]
        col = col[np.isfinite(col)]
        Y[:, d] = np.clip((Y[:, d] - col.mean()) / col.std(), -8, 8)
    return r, s, Y


# ---------------------------------------------------------------- filters (numba)
# Every filter reads Y (n, D); column 0 is the standardised close return. The forecast is
# P(next return > 0), and the reported log score is the predictive density of the *return* alone,
# so close-only and full-candle runs are scored on the same quantity.

LOG2PI = math.log(2 * math.pi)


@nb.njit(cache=True, error_model="numpy")
def gauss(y, m, s):
    z = (y - m) / s
    return math.exp(-0.5 * z * z) / (s * math.sqrt(2 * math.pi))


@nb.njit(cache=True, error_model="numpy")
def emit(Yt, mu, sd, k):
    v = 1.0
    for d in range(Yt.shape[0]):
        v *= gauss(Yt[d], mu[k, d], sd[k, d])
    return max(v, 1e-300)


@nb.njit(cache=True, error_model="numpy")
def kalman_run(Y, phi, q, rv, b, a, out_p, out_l):
    """AR(1) drift m; return = m + noise; with candles also location = a + b m + noise
    (the close's place in its bar loads on the same drift). Observations processed in turn."""
    D = min(Y.shape[1], 2)
    m, P = 0.0, q / max(1e-6, 1 - phi * phi)
    ll = 0.0
    for t in range(Y.shape[0]):
        m, P = phi * m, phi * phi * P + q
        S = P + rv[0]
        out_p[t] = 0.5 * (1 + math.erf(m / math.sqrt(2 * S)))
        e = Y[t, 0] - m
        out_l[t] = -0.5 * (LOG2PI + math.log(S) + e * e / S)
        ll += out_l[t]
        K = P / S
        m, P = m + K * e, (1 - K) * P
        if D > 1:
            S2 = b * b * P + rv[1]
            e2 = Y[t, 1] - a - b * m
            ll += -0.5 * (LOG2PI + math.log(S2) + e2 * e2 / S2)
            K2 = P * b / S2
            m, P = m + K2 * e2, (1 - K2 * b) * P
    return ll


def fit_kalman(Y):
    Yt = np.ascontiguousarray(Y[-FIT_MAX:])
    op, ol = np.empty(len(Yt)), np.empty(len(Yt))
    D = min(Y.shape[1], 2)

    def unpack(th):
        rv = np.array([math.exp(th[2]), math.exp(th[3]) if D > 1 else 1.0])
        return math.tanh(th[0]), math.exp(th[1]), rv, (th[4] if D > 1 else 0.0), (th[5] if D > 1 else 0.0)

    def nll(th):
        v = -kalman_run(Yt, *unpack(th), op, ol)
        return v if np.isfinite(v) else 1e12

    x0s = ([0.9, -6, 0, 0, 1, 0], [0.99, -9, 0, 0, 0.1, 0], [0.5, -3, 0, 0, 3, 0])
    best = min((minimize(nll, np.array(x0[:6 if D > 1 else 3], float), method="Nelder-Mead",
                         options={"maxiter": 1500}) for x0 in x0s), key=lambda r: r.fun)
    phi, q, rv, b, a = unpack(best.x)
    return dict(phi=phi, q=q, rv=rv, b=b, a=a)


@nb.njit(cache=True, error_model="numpy")
def hmm_em(Y, A, mu, sd, iters):
    n, K, D = Y.shape[0], mu.shape[0], Y.shape[1]
    al = np.empty((n, K))
    be = np.empty((n, K))
    c = np.empty(n)
    B = np.empty((n, K))
    g = np.empty((n, K))
    for _ in range(iters):
        for t in range(n):
            for k in range(K):
                B[t, k] = emit(Y[t], mu, sd, k)
        s = 0.0
        for k in range(K):
            al[0, k] = B[0, k] / K
            s += al[0, k]
        c[0] = s
        for k in range(K):
            al[0, k] /= s
        for t in range(1, n):
            s = 0.0
            for k in range(K):
                a = 0.0
                for j in range(K):
                    a += al[t - 1, j] * A[j, k]
                al[t, k] = a * B[t, k]
                s += al[t, k]
            c[t] = s
            for k in range(K):
                al[t, k] /= s
        for k in range(K):
            be[n - 1, k] = 1.0
        for t in range(n - 2, -1, -1):
            for j in range(K):
                b = 0.0
                for k in range(K):
                    b += A[j, k] * B[t + 1, k] * be[t + 1, k]
                be[t, j] = b / c[t + 1]
        num = np.zeros((K, K))
        for t in range(n):
            for k in range(K):
                g[t, k] = al[t, k] * be[t, k]
        for t in range(n - 1):
            for j in range(K):
                for k in range(K):
                    num[j, k] += al[t, j] * A[j, k] * B[t + 1, k] * be[t + 1, k] / c[t + 1]
        for j in range(K):
            rs = max(num[j].sum(), 1e-300)
            for k in range(K):
                A[j, k] = max(num[j, k] / rs, 1e-6)
            w = max(g[:, j].sum(), 1e-12)
            for d in range(D):
                m = (g[:, j] * Y[:, d]).sum() / w
                mu[j, d] = m
                sd[j, d] = max(math.sqrt((g[:, j] * (Y[:, d] - m) ** 2).sum() / w), 0.05)
    return A, mu, sd


@nb.njit(cache=True, error_model="numpy")
def hmm_run(Y, A, mu, sd, out_p, out_l, out_s):
    K = mu.shape[0]
    pi = np.ones(K) / K
    pr = np.empty(K)
    for t in range(Y.shape[0]):
        for k in range(K):
            pr[k] = 0.0
            for j in range(K):
                pr[k] += pi[j] * A[j, k]
        up, dens, marg = 0.0, 0.0, 0.0
        for k in range(K):
            up += pr[k] * 0.5 * (1 + math.erf(mu[k, 0] / (sd[k, 0] * math.sqrt(2))))
            marg += pr[k] * gauss(Y[t, 0], mu[k, 0], sd[k, 0])
            pi[k] = pr[k] * emit(Y[t], mu, sd, k)
            dens += pi[k]
        out_p[t] = up
        out_l[t] = math.log(max(marg, 1e-300))
        best, bk = -1.0, 0
        dens = max(dens, 1e-300)
        for k in range(K):
            pi[k] /= dens
            if pi[k] > best:
                best, bk = pi[k], k
        out_s[t] = bk


def init_emission(Y):
    D = Y.shape[1]
    mu = np.zeros((3, D))
    sd = np.ones((3, D))
    mu[:, 0] = (-0.3, 0.0, 0.3)
    sd[:, 0] = (1.3, 0.7, 1.0)
    for d in range(1, D):
        mu[:, d] = (-0.3, 0.0, 0.3) if d == 1 else (0.3, -0.3, 0.0)
    return mu, sd


def fit_hmm(Y):
    A = np.full((3, 3), 0.05) + np.eye(3) * 0.85
    mu, sd = init_emission(Y)
    return hmm_em(np.ascontiguousarray(Y), A, mu, sd, 60)


@nb.njit(cache=True, error_model="numpy")
def pf_run(Y, A, mu, sd, phi, sh, nu, N, seed, out_p, out_l, out_s):
    """Regime x stochastic volatility; the return is Student-t scaled by exp(h/2), candle
    columns Gaussian given the regime."""
    np.random.seed(seed)
    K, D = mu.shape[0], Y.shape[1]
    cum = np.empty((K, K))
    for j in range(K):
        a = 0.0
        for k in range(K):
            a += A[j, k]
            cum[j, k] = a
    s = np.random.randint(0, K, N)
    h = np.random.randn(N) * sh / math.sqrt(max(1e-6, 1 - phi * phi))
    w = np.empty(N)
    lc = math.lgamma((nu + 1) / 2) - math.lgamma(nu / 2) - 0.5 * math.log(nu * math.pi)
    scale_t = math.sqrt((nu - 2) / nu) if nu > 2 else 1.0
    ll = 0.0
    ns = np.empty(N, np.int64)
    nh = np.empty(N)
    for t in range(Y.shape[0]):
        up, tot, marg = 0.0, 0.0, 0.0
        cnt = np.zeros(K)
        for i in range(N):
            u = np.random.rand()
            k = 0
            while k < K - 1 and u > cum[s[i], k]:
                k += 1
            s[i] = k
            h[i] = phi * h[i] + sh * np.random.randn()
            sig = sd[k, 0] * math.exp(0.5 * h[i]) * scale_t
            up += 0.5 * (1 + math.erf(mu[k, 0] / (sig * math.sqrt(2))))
            z = (Y[t, 0] - mu[k, 0]) / sig
            f0 = math.exp(lc - 0.5 * (nu + 1) * math.log(1 + z * z / nu)) / sig
            marg += f0
            for d in range(1, D):
                f0 *= gauss(Y[t, d], mu[k, d], sd[k, d])
            w[i] = f0 + 1e-300
            tot += w[i]
        out_p[t] = up / N
        out_l[t] = math.log(max(marg / N, 1e-300))
        ll += math.log(tot / N)
        step = tot / N
        u0 = np.random.rand() * step
        j, acc = 0, w[0]
        for i in range(N):
            target = u0 + i * step
            while acc < target and j < N - 1:
                j += 1
                acc += w[j]
            ns[i], nh[i] = s[j], h[j]
        for i in range(N):
            s[i], h[i] = ns[i], nh[i]
            cnt[s[i]] += 1
        out_s[t] = np.argmax(cnt)
    return ll


def fit_particle(Y, hmm):
    A, mu, sd = hmm
    Yt = np.ascontiguousarray(Y[-8000:])
    op, ol, os_ = np.empty(len(Yt)), np.empty(len(Yt)), np.empty(len(Yt), np.int64)
    best = None
    for phi in (0.9, 0.97):
        for sh in (0.1, 0.3):
            for nu in (4.0, 30.0):
                ll = pf_run(Yt, A, mu, sd, phi, sh, nu, 400, 7, op, ol, os_)
                if best is None or ll > best[0]:
                    best = (ll, phi, sh, nu)
    return dict(phi=best[1], sh=best[2], nu=best[3])


@nb.njit(cache=True, error_model="numpy")
def q_run(Y, U, V, mu, sd, gamma, out_p, out_l, out_s):
    K = mu.shape[0]
    rho = np.eye(K).astype(np.complex128) / K
    Vh = V.conj().T
    Uh = U.conj().T
    ll = 0.0
    f = np.empty(K)
    for t in range(Y.shape[0]):
        rp = U @ rho @ Uh
        for i in range(K):
            for j in range(K):
                if i != j:
                    rp[i, j] *= 1 - gamma
        rv = Vh @ rp @ V
        up, dens, marg = 0.0, 0.0, 0.0
        best, bk = -1.0, 0
        for k in range(K):
            wk = max(rv[k, k].real, 0.0)
            f[k] = emit(Y[t], mu, sd, k)
            up += wk * 0.5 * (1 + math.erf(mu[k, 0] / (sd[k, 0] * math.sqrt(2))))
            marg += wk * gauss(Y[t, 0], mu[k, 0], sd[k, 0])
            dens += wk * f[k]
            if wk * f[k] > best:
                best, bk = wk * f[k], k
        out_p[t] = up
        out_l[t] = math.log(max(marg, 1e-300))
        ll += math.log(max(dens, 1e-300))
        out_s[t] = bk
        Dm = np.zeros((K, K), np.complex128)
        for k in range(K):
            Dm[k, k] = math.sqrt(f[k])
        M = V @ Dm @ Vh
        rho = M @ rp @ M.conj().T
        tr = 0.0
        for k in range(K):
            tr += rho[k, k].real
        if tr <= 0 or not np.isfinite(tr):
            rho = np.eye(K).astype(np.complex128) / K
        else:
            rho = rho / tr
            rho = 0.5 * (rho + rho.conj().T)
    return ll


def herm(v):
    H = np.diag(v[:3]).astype(complex)
    H[0, 1], H[0, 2], H[1, 2] = v[3] + 1j * v[4], v[5] + 1j * v[6], v[7] + 1j * v[8]
    return H + np.triu(H, 1).conj().T


def q_npar(variant, D):
    return 9 + 6 * D + {"qdecoh": 0, "qbasis": 1, "quantum": 10}[variant]


def q_unpack(th, variant, D):
    U = expm(-1j * herm(th[:9]))
    e = 9 + 3 * D
    mu, sd = th[9:e].reshape(3, D), np.exp(th[e:e + 3 * D]).reshape(3, D)
    if variant == "qdecoh":
        return U, np.eye(3, dtype=complex), mu, sd, 1.0
    g = th[e + 3 * D]
    gamma = 1 / (1 + math.exp(-g))
    V = np.eye(3, dtype=complex) if variant == "qbasis" else expm(-1j * herm(th[e + 3 * D + 1:e + 3 * D + 10]))
    return U, V, mu, sd, gamma


def fit_quantum(Y, variant, seed=0, hmm=None):
    Yt = np.ascontiguousarray(Y[-FIT_MAX:])
    D = Y.shape[1]
    op, ol, os_ = np.empty(len(Yt)), np.empty(len(Yt)), np.empty(len(Yt), np.int64)
    npar = q_npar(variant, D)

    def nll(th):
        U, V, mu, sd, g = q_unpack(th, variant, D)
        v = -q_run(Yt, U, V, mu, sd, g, op, ol, os_)
        return v if np.isfinite(v) else 1e12

    rng = np.random.default_rng(seed)
    best = None
    e = 9 + 3 * D
    for start in range(2):
        x0 = np.zeros(npar)
        x0[:9] = rng.normal(0, 0.3, 9)
        mu0, sd0 = (hmm[1], hmm[2]) if hmm is not None else init_emission(Y)
        x0[9:e] = mu0.ravel()
        x0[e:e + 3 * D] = np.log(sd0).ravel()
        if variant != "qdecoh":
            x0[e + 3 * D] = -1.0 if start == 0 else 2.0  # mostly coherent / mostly dephased
        if variant == "quantum":
            x0[e + 3 * D + 1:] = rng.normal(0, 0.3, 9)
        r = minimize(nll, x0, method="L-BFGS-B", options={"maxiter": 250})
        if best is None or r.fun < best.fun:
            best = r
    return best.x, -best.fun / len(Yt)


def run_all(Y, train_end, seed=0):
    """Fit every model on Y[:train_end]; per bar, P(return > 0) and the log density of the return,
    each made from earlier bars only."""
    Y = np.ascontiguousarray(Y)
    n, D = Y.shape
    Ytr = Y[:train_end]
    res, info = {}, {}
    k = fit_kalman(Ytr)
    p, l_ = np.empty(n), np.empty(n)
    kalman_run(Y, k["phi"], k["q"], k["rv"], k["b"], k["a"], p, l_)
    res["kalman"], info["kalman"] = (p, l_, None), {kk: (v.tolist() if hasattr(v, "tolist") else v) for kk, v in k.items()}
    hmm = fit_hmm(Ytr[-FIT_MAX * 2:])
    A, mu, sd = hmm
    p, l_, s = np.empty(n), np.empty(n), np.empty(n, np.int64)
    hmm_run(Y, A, mu, sd, p, l_, s)
    res["hmm"], info["hmm"] = (p, l_, s), dict(mu=mu[:, 0].tolist(), sd=sd[:, 0].tolist(), stay=np.diag(A).tolist())
    pp = fit_particle(Ytr, hmm)
    p, l_, s = np.empty(n), np.empty(n), np.empty(n, np.int64)
    pf_run(Y, A, mu, sd, pp["phi"], pp["sh"], pp["nu"], 1000, 11 + seed, p, l_, s)
    res["particle"], info["particle"] = (p, l_, s), pp
    for v in ("qdecoh", "qbasis", "quantum"):
        th, llt = fit_quantum(Ytr, v, seed, hmm)
        U, V, mu_, sd_, g = q_unpack(th, v, D)
        p, l_, s = np.empty(n), np.empty(n), np.empty(n, np.int64)
        q_run(Y, U, V, mu_, sd_, g, p, l_, s)
        res[v], info[v] = (p, l_, s), dict(gamma=g, train_ll=llt, npar=q_npar(v, D), mu=mu_[:, 0].tolist())
    y0 = Ytr[:, 0]
    nu, loc, sc = student.fit(y0[np.isfinite(y0)], floc=0)
    info["rw"] = dict(nu=nu, scale=sc)
    res["rw"] = (np.full(n, 0.5), student.logpdf(Y[:, 0], nu, 0, sc), None)
    return res, info


# ---------------------------------------------------------------- scoring

def auc(y, p):
    if len(np.unique(y)) < 2:
        return np.nan
    return roc_auc_score(y, p)


def boot_auc(y, p, block, reps=300, seed=0):
    """Block-bootstrap AUC: whole days resampled, because filtered states persist."""
    rng = np.random.default_rng(seed)
    n = len(y)
    nb_ = max(1, n // block)
    vals = []
    for _ in range(reps):
        starts = rng.integers(0, n - block, nb_)
        idx = (starts[:, None] + np.arange(block)).ravel()
        vals.append(auc(y[idx], p[idx]))
    vals = np.array(vals)
    return np.nanpercentile(vals, 2.5), np.nanpercentile(vals, 97.5), float(np.mean(vals <= 0.5))


def trade_stats(r, p, cost, thr=None):
    """Always-in sign(P - 0.5) next bar, cost on each flip; and the confident subset."""
    pos = np.sign(p - 0.5)
    flips = np.abs(np.diff(np.r_[0, pos])) / 2
    gross = pos * r
    net = gross - flips * cost
    out = dict(gross_bps=1e4 * np.nanmean(gross), net_bps=1e4 * np.nanmean(net),
               t_net=np.nanmean(net) / (np.nanstd(net) / np.sqrt(len(net))))
    if thr is not None:
        k = np.abs(p - 0.5) >= thr
        if k.sum() >= 30:
            g = pos[k] * r[k]
            out.update(conf_n=int(k.sum()), conf_gross_bps=1e4 * np.mean(g),
                       conf_net_bps=1e4 * np.mean(g - cost),
                       conf_t=np.mean(g - cost) / (np.std(g) / np.sqrt(k.sum())))
    return out


def paths(df, idx, H):
    lc = np.log(df.close.to_numpy())
    n = len(lc)
    idx = idx[idx + H < n]
    cols = {c: np.log(df[c].to_numpy()) for c in ("open", "high", "low", "close")}
    P = Bars(*(np.column_stack([cols[c][idx + k] - lc[idx] for k in range(1, H + 1)])
               for c in ("open", "high", "low", "close")))
    return idx, P


def tail(df, idx, side, stop, cost):
    """Enter at the close toward `side`, stop one bar-sigma away, no target: P(>= 4R), P(>= 10R)
    before the stop within 100 bars, non-overlapping. Against 1/(N+1)."""
    idx, P = paths(df, np.asarray(idx), TAIL_H)
    if len(idx) < 30:
        return None
    side = pd.Series(side, index=None).to_numpy()[:len(idx)]
    stop = np.asarray(stop)[:len(idx)]
    P = P * side
    out = {"n": len(idx)}
    keep = np.ones(len(idx), bool)
    last = -10**9
    w_end = np.zeros(len(idx), int)
    # non-overlap: the next trade waits until this one's stop, or 100 bars
    hit = (P.l <= -stop[:, None])
    first = np.where(hit.any(1), hit.argmax(1), TAIL_H - 1)
    for i, (t, f) in enumerate(zip(idx, first)):
        if t <= last:
            keep[i] = False
        else:
            last = t + f + 1
    P2 = Bars(P.o[keep], P.h[keep], P.l[keep], P.c[keep])
    st = stop[keep]
    out["n"] = int(keep.sum())
    for N in (4, 10):
        w, _ = race(P2, N * st, st)
        out[f"p{N}"] = float(np.mean(w > 0))
    out["cost_R"] = float(np.mean(cost / st))
    return out


# ---------------------------------------------------------------- the zone method (zone-fill.md)

ZH, LOOK = 8, 50


def zone_rows(df):
    lo_, hi_, lc = np.log(df.low), np.log(df.high), np.log(df.close)
    r = lc.diff()
    base = r.abs().rolling(500, min_periods=250).mean()
    speed = r.abs().rolling(10).mean() / base
    eff = (lc - lc.shift(20)) / r.abs().rolling(20).sum()
    vel = r.rolling(5).mean() / base
    # the last candle, whole: where it closed in its range, its body, each wick, its range
    o, h, l_, c = (df[k] for k in ("open", "high", "low", "close"))
    span = (h - l_).where(h > l_)
    loc = ((c - (h + l_) / 2) / span).fillna(0)
    body = (np.log(c) - np.log(o)) / base
    wick_to = (np.log(h) - np.log(np.maximum(o, c))) / base     # upper wick
    wick_away = (np.log(np.minimum(o, c)) - np.log(l_)) / base  # lower wick
    rng_ = (np.log(h) - np.log(l_)) / base
    out = []
    for side in (1, -1):
        level = hi_.shift(1).rolling(LOOK).max() if side > 0 else lo_.shift(1).rolling(LOOK).min()
        dist = side * (level - lc) / base
        band = 0.25 * base
        if side > 0:
            cluster = sum((hi_.shift(k) >= level - band).astype(float) for k in range(1, LOOK + 1))
        else:
            cluster = sum((lo_.shift(k) <= level + band).astype(float) for k in range(1, LOOK + 1))
        z = pd.DataFrame({"t": np.arange(len(df)), "side": side, "dist": dist, "size": cluster,
                          "speed": speed, "velocity": side * vel, "efficiency": side * eff, "base": base,
                          "c_loc": side * loc, "c_body": side * body, "c_wick": wick_to if side > 0 else wick_away,
                          "c_wick_away": wick_away if side > 0 else wick_to, "c_range": rng_})
        out.append(z[z.dist > 0])
    return pd.concat(out, ignore_index=True)


def zone_study(df, cost_rel, htf_p=None):
    z = zone_rows(df)
    if htf_p is not None:
        z["htf"] = z.side * (htf_p[z.t.to_numpy()] - 0.5)
    lc = np.log(df.close.to_numpy())
    idx, P = paths(df, z.t.to_numpy(), ZH)
    z = z[z.t.isin(idx)].reset_index(drop=True)
    idx, P = paths(df, z.t.to_numpy(), ZH)
    P = P * z.side.to_numpy()
    reach = z.dist.to_numpy() * z.base.to_numpy()
    z["filled"] = (np.nanmax(P.h, 1) >= reach).astype(float)
    sigma = z.base.to_numpy() * np.sqrt(np.pi / 2)
    z["physics"] = np.clip(2 * (1 - norm.cdf(reach / (sigma * np.sqrt(ZH)))), 0, 1)
    for k in (1, 2):
        R, _ = long_R(P, reach, k * reach)
        z[f"R{k}"] = R - cost_rel / (k * reach)
    cols = ["dist", "size", "speed", "velocity", "efficiency"] + (["htf"] if htf_p is not None else [])
    z = z.replace([np.inf, -np.inf], np.nan).dropna(subset=cols + ["R1", "c_body", "c_range"])
    X = z[cols].to_numpy(float)
    X[:, 0] = np.log(X[:, 0])
    X[:, 1] = np.log1p(X[:, 1])
    te = (z.t >= z.t.quantile(TRAIN)).to_numpy()
    y = z.filled.to_numpy()
    res = {"n_test": int(te.sum()), "fill_rate": float(y[te].mean())}
    res["auc_physics"] = auc(y[te], z.physics.to_numpy()[te])
    m = LogisticRegression(max_iter=2000).fit(X[~te][:, :5], y[~te])
    p = m.predict_proba(X[:, :5])[:, 1]
    res["auc_method"] = auc(y[te], p[te])
    res["coef"] = dict(zip(cols[:5], np.round(m.coef_[0], 3).tolist()))
    cc = ["c_loc", "c_body", "c_wick", "c_wick_away", "c_range"]
    Xc = np.column_stack([X[:, :5], z[cc].to_numpy(float)])
    mc = LogisticRegression(max_iter=2000).fit(Xc[~te], y[~te])
    res["auc_method_candle"] = auc(y[te], mc.predict_proba(Xc)[:, 1][te])
    res["coef_candle"] = dict(zip(cc, np.round(mc.coef_[0][5:], 3).tolist()))
    if htf_p is not None:
        m2 = LogisticRegression(max_iter=2000).fit(X[~te], y[~te])
        res["auc_method_htf"] = auc(y[te], m2.predict_proba(X)[:, 1][te])
        res["coef_htf"] = float(m2.coef_[0][-1])
    calib = {}
    for lo, hi in ((0.8, 0.95), (0.95, 0.99), (0.99, 1.01)):
        k = te & (p >= lo) & (p < hi)
        calib[f"{lo:.2f}"] = (int(k.sum()), float(p[k].mean()) if k.sum() else None,
                              float(y[k].mean()) if k.sum() else None)
    res["calibration"] = calib
    # trade toward the most probable zone each bar, non-overlapping
    z["p"] = p
    zt = z[te]
    best = zt.loc[zt.groupby("t").p.idxmax()].sort_values("t")
    keep, last = [], -10**9
    for i, t in zip(best.index, best.t):
        if t - last >= ZH:
            keep.append(i)
            last = t
    b = best.loc[keep]
    trades = {}
    for label, sel in (("all", b.p >= 0), ("p>=0.80", b.p >= 0.8), ("p>=0.95", b.p >= 0.95),
                       ("p>=0.99", b.p >= 0.99)):
        s = b[sel]
        trades[label] = dict(n=int(len(s)), net_R1=float(s.R1.mean()) if len(s) else None,
                             net_R2=float(s.R2.mean()) if len(s) else None,
                             win1=float((s.R1 > 0).mean()) if len(s) else None)
    res["trades"] = trades
    # the tail version: same direction, stop one bar-sigma, no target
    top = b[b.p >= b.p.quantile(0.8)]
    res["tail"] = tail(df, top.t.to_numpy(), top.side.to_numpy(),
                       (top.base * np.sqrt(np.pi / 2)).to_numpy(), cost_rel)
    return res


