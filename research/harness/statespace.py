def score_series(df, tf, cost_rel, seed=0, obs="close"):
    n = len(df)
    tr_end = int(n * TRAIN)
    r, s, Y = observations(df, obs, tr_end)
    ok = np.isfinite(Y).all(axis=1)
    first = int(np.argmax(ok))
    Yy = np.where(np.isfinite(Y), Y, 0.0)
    y = Y[:, 0]
    res, info = run_all(Yy[first:], tr_end - first, seed)
    full = {}
    for m, (p, l_, st) in res.items():
        pf = np.full(n, np.nan)
        lf = np.full(n, np.nan)
        pf[first:], lf[first:] = p, l_
        full[m] = (pf, lf)
    te = np.arange(n) >= tr_end
    te &= np.isfinite(r) & np.isfinite(y)
    up = (r[te] > 0).astype(int)
    out = {"n": int(n), "n_test": int(te.sum()), "info": info, "models": {}}
    rw_l = full["rw"][1][te]
    for m in MODELS:
        p, l_ = full[m]
        thr = np.nanquantile(np.abs(p[~te & np.isfinite(p)] - 0.5), 0.9)
        lo, hi, pval = boot_auc(up, p[te], DAYBARS[tf])
        row = dict(auc=auc(up, p[te]), lo=lo, hi=hi, p=pval,
                   logscore_mnats=1000 * float(np.mean(l_[te] - rw_l)))
        row.update(trade_stats(r[te], p[te], cost_rel, thr))
        # the tail trade on the confident calls
        k = np.where(te & (np.abs(p - 0.5) >= thr))[0]
        row["tail"] = tail(df, k, np.sign(p[k] - 0.5), s[k] if len(k) else [], cost_rel) if len(k) else None
        out["models"][m] = row
    out["p_series"] = {m: full[m][0] for m in MODELS}
    return out


def job(args):
    sym, tf, kind, seed = args
    df = load(sym, tf)
    rng = np.random.default_rng(1000 + seed)
    if kind == "flip":
        df = flip_walk(df, rng)
    elif kind == "garch":
        df = garch_walk(df, rng)
    cost = spread_rel(sym)
    out = dict(sym=sym, tf=tf, kind=kind, seed=seed, zone=zone_study(df, cost))
    for obs in ("close", "ohlc"):
        out[obs] = one_obs(df, sym, tf, cost, seed, obs)
    return out


def one_obs(df, sym, tf, cost, seed, obs):
    res = score_series(df, tf, cost, seed, obs)
    ps = res.pop("p_series")
    # multi-timeframe: higher frames built from this series
    mtf = {}
    for lt, ht in MTF:
        if lt != tf:
            continue
        hdf = aggregate(df, lt, ht)
        if len(hdf) < 600:
            continue
        hres = score_series(hdf[["time", "open", "high", "low", "close"]].reset_index(drop=True), ht, cost, seed, obs)
        hp = hres.pop("p_series")
        close_h = (hdf.time + MIN[ht] * 60).to_numpy()
        close_l = (df.time + MIN[lt] * 60).to_numpy()
        j = np.searchsorted(close_h, close_l, side="right") - 1  # last higher bar closed by now
        valid = j >= 0
        r = np.diff(np.log(df.close.to_numpy()), prepend=np.nan)
        n = len(df)
        te = (np.arange(n) >= int(n * TRAIN)) & np.isfinite(r)
        upn = (r > 0).astype(int)
        row = {"htf_auc_alone": {}, "combined": {}, "agree": {}}
        for m in ("hmm", "quantum", "kalman"):
            hpm = np.full(n, np.nan)
            hpm[valid] = hp[m][j[valid]]
            lp = ps[m]
            good = np.isfinite(hpm) & np.isfinite(lp) & np.isfinite(r)
            trn, tst = good & ~te, good & te
            if tst.sum() < 200 or trn.sum() < 200:
                continue
            X = np.nan_to_num(np.column_stack([lp - 0.5, hpm - 0.5]))
            lr = LogisticRegression().fit(X[trn], upn[trn])
            pc = lr.predict_proba(X)[:, 1]  # read on `tst` rows only, where both are finite
            row["htf_auc_alone"][m] = auc(upn[tst], hpm[tst])
            row["combined"][m] = dict(ltf=auc(upn[tst], lp[tst]), both=auc(upn[tst], pc[tst]))
            agree = tst & (np.sign(lp - 0.5) == np.sign(hpm - 0.5))
            g = np.sign(lp[agree] - 0.5) * r[agree]
            dis = tst & ~agree
            gd = np.sign(lp[dis] - 0.5) * r[dis]
            row["agree"][m] = dict(share=float(agree.sum() / tst.sum()),
                                   hit=float(np.mean(g > 0)), hit_disagree=float(np.mean(gd > 0)),
                                   gross_bps=1e4 * float(np.mean(g)), net_bps=1e4 * float(np.mean(g - cost)))
            if m == "hmm" and obs == "ohlc":
                row["zone_htf"] = zone_study(df, cost, hpm)
        row["htf_models"] = {m: hres["models"][m]["auc"] for m in MODELS}
        mtf[ht] = row
    res["mtf"] = mtf
    return res


# ---------------------------------------------------------------- synthetic positive controls

def synth_hmm(n, rng):
    A = np.array([[0.98, 0.01, 0.01], [0.01, 0.98, 0.01], [0.01, 0.01, 0.98]])
    mu, sd = np.array([-0.15, 0.0, 0.15]), np.array([1.0, 0.7, 1.0])
    s = np.empty(n, int)
    s[0] = 1
    for t in range(1, n):
        s[t] = rng.choice(3, p=A[s[t - 1]])
    return mu[s] + sd[s] * rng.standard_normal(n), s, (A, mu, sd)


def synth_quantum(n, rng):
    H = herm(rng.normal(0, 0.15, 9))
    U, V = expm(-1j * H), expm(-1j * herm(rng.normal(0, 0.8, 9)))
    mu, sd = np.array([-0.4, 0.0, 0.4]), np.array([1.0, 0.6, 1.0])
    rho = np.eye(3, dtype=complex) / 3
    y, s = np.empty(n), np.empty(n, int)
    for t in range(n):
        rp = U @ rho @ U.conj().T
        w = np.clip(np.real(np.diag(V.conj().T @ rp @ V)), 0, None)
        k = rng.choice(3, p=w / w.sum())
        y[t], s[t] = mu[k] + sd[k] * rng.standard_normal(), k
        f = np.array([norm.pdf(y[t], mu[i], sd[i]) for i in range(3)])
        M = V @ np.diag(np.sqrt(f)) @ V.conj().T
        rho = M @ rp @ M.conj().T
        rho /= np.real(np.trace(rho))
    return y, s, (U, V, mu, sd)


def regime_acc(s_true, s_hat):
    from itertools import permutations
    return max(np.mean(np.array(perm)[s_hat] == s_true) for perm in permutations(range(3)))


def synth_job(which):
    rng = np.random.default_rng(42 if which == "S1" else 43)
    n = 30000
    y, s, truth = (synth_hmm if which == "S1" else synth_quantum)(n, rng)
    tr = int(n * TRAIN)
    res, info = run_all(y[:, None], tr)
    te = np.arange(n) >= tr
    up = (y[te] > 0).astype(int)
    p, l_, st = np.empty(n), np.empty(n), np.empty(n, np.int64)
    if which == "S1":
        A, mu, sd = truth
        hmm_run(y[:, None], A.copy(), mu[:, None], sd[:, None], p, l_, st)
    else:
        U, V, mu, sd = truth
        q_run(y[:, None], U, V, mu[:, None], sd[:, None], 0.0, p, l_, st)
    out = {"oracle": dict(auc=auc(up, p[te]), logscore_mnats=1000 * float(np.mean(l_[te] - res["rw"][1][te])),
                          regime=regime_acc(s[te], st[te]))}
    for m in MODELS:
        pm, lm, sm = res[m]
        out[m] = dict(auc=auc(up, pm[te]), logscore_mnats=1000 * float(np.mean(lm[te] - res["rw"][1][te])),
                      regime=regime_acc(s[te], sm[te]) if sm is not None else None)
    out["info"] = {k: v for k, v in info.items() if k.startswith("q")}
    return which, out


