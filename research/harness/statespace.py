"""State-space filters (Kalman, HMM, particle, quantum density matrix) and the zone-fill method,
on EURUSD and Volatility 75 at 15m, 1h, 4h and 1d, with matched walks and multi-timeframe joins.

The question comes from two sources (`research/papers/state-space.md`):

- a research note proposing a ladder Kalman -> particle -> quantum state space, and asking whether
  a density-matrix state with coherence beats Kalman, HMM and particle filters out of sample;
- a trader's "particle physics" method: estimate the probability that price fills each liquidity
  zone from speed, directional efficiency, zone size and distance, and trade the most probable
  zone, at first only at probability 1.

The second was measured on 21 other series in `zone-fill.md`; here it is repeated on the two
instruments asked for, at all four desk timeframes, against walks we generate ourselves, and with
a higher-timeframe state reading added as an input.

## The filters (all fitted on the first 60% of each series by time, scored on the last 40%)

The observation is the bar's log return over the EWMA sigma known before it,
`y_t = r_t / s_{t-1}` (lambda 0.94), so every model is asked about direction and shape, not the
level of volatility.

  rw        Student-t, zero mean - the yardstick for the log score
  kalman    AR(1) latent drift: m_t = phi m_{t-1} + w, y_t = m_t + v (Gaussian, MLE)
  hmm       3-state Gaussian HMM, Baum-Welch, forward-filtered only (no smoothing)
  particle  3 regimes x stochastic volatility, Student-t emission, 1,000 particles
  qdecoh    the quantum filter with its coherence removed: dephased every step, measured in the
            regime basis - a classical HMM with a unistochastic transition matrix
  qbasis    coherence kept, measured in the regime basis
  quantum   coherence kept and a rotated measurement basis (a non-commuting POVM)

The quantum filter: rho_pred = D_gamma(U rho U^dag) with U = exp(-iH) and D_gamma scaling the
off-diagonals by (1 - gamma); the measurement operators are M_y = V diag(sqrt f_k(y)) V^dag, which
integrate to the identity, so p(y) = Tr(M_y rho M_y^dag) = sum_k f_k(y) (V^dag rho V)_kk is a proper
density, and rho <- M_y rho M_y^dag / p(y). gamma = 1 with V = I is exactly a classical HMM, which is
the ablation the note asks for.

## Positive controls (synthetic, truth known)

  S1  a classical 3-regime switching series - an HMM should recover the regimes
  S2  a series generated by the quantum filter itself, with strong coherence - if coherence carries
      anything, the quantum filter must beat the HMM here, or the test has no power

## Walks

  flip   each real bar mirrored about the previous close with a random sign: the volatility path,
         bar shapes and gaps are exactly the real ones, direction is a coin
  garch  GARCH(1,1)-t at the real unconditional variance, OHLC from 8 sub-steps a bar

## Multi-timeframe

Higher-timeframe bars are aggregated from the lower one (15m -> 1h, 4h; 1h -> 4h, 1d; 4h -> 1d)
so real and walk are treated identically. A higher bar's reading is joined to a lower bar only once
the higher bar has closed (asof on close times).

Run on the lab (BARS holds `pipeline_bars/` and `broker/` as the desk's bar exports lay them out):
  ./.secrets/lab.sh run research/harness/statespace.py BARS=<bars> OUT=<out> WORKERS=26 OMP_NUM_THREADS=1
"""

