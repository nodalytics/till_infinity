def detect(mid: np.ndarray) -> dict:
    """`derivejump.py`'s estimator, unchanged: a spike is a tick move past 10x
    the median absolute move, and the spike side is the rarer sign."""
    d = np.diff(mid)
    nz = np.abs(d[d != 0])
    if not nz.size:
        return {}
    med = float(np.median(nz))
    spike = np.abs(d) > SPIKE_MULT * med
    side = +1 if int((d > 0).sum()) < int((d < 0).sum()) else -1
    J = np.abs(d[spike & (np.sign(d) == side)])
    g = np.abs(d[~spike])
    if J.size < 20 or g.size < 1000:
        return {"n_spikes": int(J.size)}
    n = d.size
    p = J.size / n
    idx = np.flatnonzero(spike)
    gaps = np.diff(idx).astype(float)
    closure = (1.0 - p) * float(g.mean()) - p * float(J.mean())
    se = float(d.std(ddof=1) / math.sqrt(n))
    return {"n_ticks": n, "side": side, "p": p, "lam": 1.0 / p, "n_spikes": int(J.size),
            "ticks_per_spike": n / J.size,
            "g_mean": float(g.mean()), "g_cv": float(g.std(ddof=1) / g.mean()),
            "J_mean": float(J.mean()), "J_med": float(np.median(J)),
            "gap_cv": float(gaps.std(ddof=1) / gaps.mean()) if gaps.size > 2 else float("nan"),
            "closure": closure, "closure_se": se, "closure_z": closure / se if se else float("nan"),
            "_g": g, "_J": J}


def hold_stats(mid: np.ndarray, nhold: int, side: int) -> dict:
    if mid.size <= nhold + 10:
        return {}
    r = (mid[:-nhold] - mid[nhold:]) if side > 0 else (mid[nhold:] - mid[:-nhold])
    nb = r[::nhold]
    return {"n": int(r.size), "mean": float(r.mean()), "median": float(np.median(r)),
            "sd": float(r.std(ddof=1)), "p_profit": float((r > 0).mean()),
            "se_mean": float(nb.std(ddof=1) / math.sqrt(nb.size)) if nb.size > 2 else float("nan"),
            "q": {q: float(np.percentile(r, q)) for q in QUANTILES}, "_r": r}


def slippage(mid: np.ndarray, dist: float, tgt_d: float, side: int, cap: int) -> dict:
    """`derivejump.py`'s `measured_slippage`, unchanged, run on both paths.

    `side` is the direction of the *trade*, so a short on the spike side of Boom
    is side = -1 when the spikes point up.
    """
    m = mid[:cap]
    n = m.size
    i = 0
    slips, losses = [], []
    stops = tot = 0
    while i < n - 2:
        e = m[i]
        stop = e - side * dist
        tgt = e + side * tgt_d
        out = None
        for j in range(i + 1, min(i + 1 + 7200, n)):
            p = m[j]
            if side * (p - stop) <= 0:
                out = ("stop", p, j - i)
                break
            if side * (p - tgt) >= 0:
                out = ("target", p, j - i)
                break
        if out is None:
            i += 7200
            continue
        why, xp, held = out
        gross = side * (xp - e)
        tot += 1
        if why == "stop":
            stops += 1
            slips.append(-(gross + dist) / dist)
            losses.append(gross / dist)
        i += max(held, 1)
    if tot < 20 or not slips:
        return {}
    s = np.array(slips)
    return {"n": tot, "p_stop": stops / tot, "mean_slip_R": float(s.mean()),
            "p90_slip_R": float(np.percentile(s, 90)), "max_slip_R": float(s.max()),
            "frac_over_half_R": float((s > 0.5).mean()),
            "mean_loss_R": float(np.mean(losses))}


def build(fit: dict, grid: float, p0: float, n_bars: int, seed: int,
          pool: bool, lam_mult: float = 1.0, keep_ticks: int = KEEP_TICKS,
          close: bool = False) -> dict:
    # The seed is (run seed, feed, which build) so that six feeds and two builds
    # do not share one Gaussian stream - seeding them alike would make twelve
    # comparisons into two and put identical numbers down a column.
    rng = np.random.default_rng([int(seed),
                                 abs(hash(fit.get("tag", "-"))) % (2 ** 31)])
    # `close` imposes E[J] = lambda*E[g] instead of using the two fitted means as
    # given. `rebuildpaper.py` found the *published* pair misses its own closure
    # by 6-12% on all six feeds, so a path built from both is not a martingale;
    # the same question is worth asking of the pair fitted here. The median is
    # scaled with the mean so the lognormal keeps its shape.
    j_mean, j_med = fit["J_mean"], fit["J_med"]
    if close:
        forced = fit["lam"] * fit["g_mean"]
        j_med = j_med * forced / j_mean
        j_mean = forced
    stream = G.gen_boomcrash(
        n_bars * TPB, fit["lam"] * lam_mult, fit["g_mean"], fit["g_cv"],
        j_mean, j_med, fit["side"], p0, grid, rng,
        grind_pool=fit["_g"] if pool else None,
        jump_pool=fit["_J"] if pool else None)
    return G.bars_from_stream(stream, TPB, n_bars,
                              keep_ticks=min(n_bars * TPB, keep_ticks))


def main() -> None:
    rng = np.random.default_rng(31337)
    ledger: list[dict] = []
    payload: dict = {"seeds": SEEDS, "bmult": BMULT}
    print("=" * 124)
    print("REBUILDING BOOM AND CRASH AS THE COMPOUND POISSON PROCESS `deriving.md` SPECIFIES")
    print(f"  seeds {SEEDS}   rebuild = {BMULT}x the 60-day bar sample "
          f"= {BMULT * 60}x the tick sample   {G.machine()}")
    print("=" * 124)

    print("\n[1] THE FEED - the five numbers the `spec` rebuild is allowed to know")
    print(f"{'feed':22s} {'ticks':>7s} {'spikes':>7s} {'lambda':>8s} {'E[g]':>10s} "
          f"{'CV[g]':>7s} {'E[J]':>10s} {'med J':>9s} {'closure z':>10s} {'gap CV':>7s} "
          f"{'spread':>9s} {'grid':>9s}")
    real = {}
    for feed in FEEDS:
        t = G.real_ticks(feed)
        b = G.real_bars(feed)
        if not t.get("n") or not b.get("n"):
            continue
        f = detect(t["mid"])
        if not f.get("n_ticks"):
            print(f"{feed:22s}  no fit")
            continue
        f["spread"] = float(np.median(t["spread"]))
        f["grid"] = G.quote_grid(t["mid"])
        f["p0"] = float(b["close"][0])
        f["_mid"] = t["mid"]
        f["_bars"] = b
        real[feed] = f
        print(f"{feed:22s} {f['n_ticks']:7d} {f['n_spikes']:7d} {f['lam']:8.1f} "
              f"{f['g_mean']:10.5f} {f['g_cv']:7.3f} {f['J_mean']:10.4f} {f['J_med']:9.4f} "
              f"{f['closure_z']:+10.2f} {f['gap_cv']:7.3f} {f['spread']:9.4f} {f['grid']:9.5g}")

    print("\n[2] THE REBUILD - the rate, recovered by the same detector")
    print(f"{'feed':22s} {'build':>6s} {'ticks/spike':>12s} {'sd':>8s} {'feed':>11s} "
          f"{'Poisson SE':>11s} {'ratio':>7s} {'gap CV':>7s} {'grind CV':>9s} "
          f"{'closure z':>10s}")
    sims: dict[str, dict[str, list]] = {}
    for feed, f in real.items():
        n_bars = min(f["_bars"]["n"] * BMULT, 260_000)
        sims[feed] = {}
        pse = f["ticks_per_spike"] / math.sqrt(f["n_spikes"])
        for tag, pool, closed in (("spec", False, False), ("closed", False, True),
                                  ("pool", True, False)):
            runs = []
            f["tag"] = f"{feed}/{tag}"
            for k, sd in enumerate(SEEDS):
                bb = build(f, f["grid"], f["p0"], n_bars, sd, pool, close=closed)
                d2 = detect(bb["ticks"])
                rr2 = G.logrets(bb["close"], bb["ts"])
                keep = {"fit": d2, "ann": G.ann_vol(rr2), "kurt": G.kurtosis(rr2),
                        "vr10": G.variance_ratio(rr2, 10),
                        "drift_z": float(rr2.mean() / (rr2.std(ddof=1)
                                                       / math.sqrt(rr2.size)))}
                # only the first seed's path is retained; the rest are summarised
                if k == 0:
                    keep["bars"] = bb
                    keep["_rets"] = rr2
                else:
                    d2.pop("_g", None)
                    d2.pop("_J", None)
                runs.append(keep)
            sims[feed][tag] = runs
            tps = G.spread_across([r["fit"]["ticks_per_spike"] for r in runs])
            gcv = G.spread_across([r["fit"]["gap_cv"] for r in runs])
            gv = G.spread_across([r["fit"]["g_cv"] for r in runs])
            cz = G.spread_across([r["fit"]["closure_z"] for r in runs])
            print(f"{feed:22s} {tag:>6s} {tps['mean']:12.1f} {tps['sd']:8.2f} "
                  f"{f['ticks_per_spike']:11.1f} {pse:11.1f} "
                  f"{tps['mean'] / f['ticks_per_spike']:7.3f} {gcv['mean']:7.3f} "
                  f"{gv['mean']:9.3f} {cz['mean']:+10.2f}", flush=True)
            ledger.append({"test": f"[{tag}] rebuilt spike rate within Poisson error of the feed",
                           "feed": feed,
                           "value": tps["mean"] / f["ticks_per_spike"] - 1.0,
                           "fired": abs(tps["mean"] - f["ticks_per_spike"]) > 2 * pse})
            # The rebuild carries sixty times the feed's ticks, so its own SE on
            # the closure is eight times smaller and a drift the feed cannot see
            # would fail a test written against the rebuild's SE. The comparison
            # that means something is at the *feed's* resolution.
            cl_ = G.spread_across([r["fit"]["closure"] for r in runs])
            czf = cl_["mean"] / f["closure_se"]
            ledger.append({"test": f"[{tag}] closure within 2 of the feed's own SE",
                           "feed": feed, "value": czf, "fired": abs(czf) > 2})
            ledger.append({"test": f"[{tag}] grind CV in 0.63-0.68", "feed": feed,
                           "value": gv["mean"], "fired": not (0.63 <= gv["mean"] <= 0.68)})
            ledger.append({"test": f"[{tag}] spike-gap CV in 0.85-1.15", "feed": feed,
                           "value": gcv["mean"], "fired": not (0.85 <= gcv["mean"] <= 1.15)})
            if G.exactly_null(cz["mean"], 0.0):
                ledger.append({"test": "VOID: closure exactly zero", "feed": feed,
                               "value": 0.0, "fired": True})

    print("\n    the ordering 300 < 500 < 1000, which is a prediction that does not depend")
    print("    on where the detector's threshold sits:")
    for fam in ("boom", "crash"):
        got = [(n, G.spread_across([r["fit"]["ticks_per_spike"]
                                    for r in sims[f"{fam}_{n}_index"]["spec"]])["mean"])
               for n in (300, 500, 1000) if f"{fam}_{n}_index" in sims]
        ordered = all(a[1] < b[1] for a, b in zip(got, got[1:], strict=False))
        print(f"      {fam:6s} rebuilt " + "  ".join(f"{n}:{v:.0f}" for n, v in got)
              + f"   ordered: {ordered}")
        ledger.append({"test": "rebuilt family orders 300 < 500 < 1000", "feed": fam,
                       "value": float(len(got)), "fired": not ordered})

    print("\n[3] THE MARGINALS - grind and jump, real against rebuilt")
    print(f"{'feed':22s} {'build':>6s} {'grind KS D':>11s} {'p':>8s} {'n*':>11s} | "
          f"{'jump KS D':>10s} {'p':>8s} {'n*':>11s} | {'J q99 real':>11s} {'sim':>10s}")
    for feed, f in real.items():
        for tag in ("spec", "closed", "pool"):
            s = sims[feed][tag][0]["fit"]
            kg = G.ks2(f["_g"], s["_g"], rng=rng)
            kj = G.ks2(f["_J"], s["_J"], rng=rng)
            print(f"{feed:22s} {tag:>6s} {kg['D']:11.5f} {kg['p']:8.4f} "
                  f"{G.nstar(kg['D']):11.3g} | {kj['D']:10.5f} {kj['p']:8.4f} "
                  f"{G.nstar(kj['D']):11.3g} | {np.percentile(f['_J'], 99):11.3f} "
                  f"{np.percentile(s['_J'], 99):10.3f}")
            payload.setdefault("marginals", {}).setdefault(feed, {})[tag] = {
                "grind_ks": kg, "jump_ks": kj}
            ledger.append({"test": f"[{tag}] grind marginal: KS does not reject", "feed": feed,
                           "value": kg["p"], "fired": kg["reject"]})
            ledger.append({"test": f"[{tag}] jump marginal: KS does not reject", "feed": feed,
                           "value": kj["p"], "fired": kj["reject"]})

    print("\n[4] THE P&L OF AN N-TICK HOLD ON THE GRIND SIDE - rebuilt against the feed")
    print("    `derivejump.py` checked its derived *law* against this; here it is the")
    print("    rebuilt *path*, which is the stronger comparison.")
    for feed, f in real.items():
        print(f"\n  {feed}  (lambda {f['lam']:.0f}, ln2*lambda {f['lam'] * math.log(2):.0f})")
        print(f"{'N':>6s} {'':>6s} {'mean':>11s} {'+-se':>10s} {'median':>11s} {'sd':>11s} "
              f"{'P(profit)':>10s} {'q01':>11s} {'q99':>11s}")
        for N in HOLDS:
            e = hold_stats(f["_mid"], N, f["side"])
            if not e:
                continue
            print(f"{N:6d} {'feed':>6s} {e['mean']:11.4f} {e['se_mean']:10.4f} "
                  f"{e['median']:11.4f} {e['sd']:11.4f} {e['p_profit']:10.4f} "
                  f"{e['q'][1]:11.4f} {e['q'][99]:11.4f}")
            for tag in ("spec", "closed", "pool"):
                s = hold_stats(sims[feed][tag][0]["bars"]["ticks"][:2_000_000], N, f["side"])
                if not s:
                    continue
                print(f"{'':6s} {tag:>6s} {s['mean']:11.4f} {s['se_mean']:10.4f} "
                      f"{s['median']:11.4f} {s['sd']:11.4f} {s['p_profit']:10.4f} "
                      f"{s['q'][1]:11.4f} {s['q'][99]:11.4f}")
                dp = abs(s["p_profit"] - e["p_profit"])
                se = math.sqrt(0.25 / max(e["n"] / N, 1))
                ledger.append({"test": f"[{tag}] P(profit) of an N-tick hold within 3 SE",
                               "feed": f"{feed} N={N}", "value": dp / se if se else 0.0,
                               "fired": dp > 3 * se})
                dsd = s["sd"] / e["sd"] - 1.0
                ledger.append({"test": f"[{tag}] sd of an N-tick hold within 15%",
                               "feed": f"{feed} N={N}", "value": dsd, "fired": abs(dsd) > 0.15})
                payload.setdefault("holds", {}).setdefault(feed, {}).setdefault(
                    tag, {})[str(N)] = {"feed": {k: v for k, v in e.items() if k != "_r"},
                                        "sim": {k: v for k, v in s.items() if k != "_r"}}

    print("\n[5] THE STOP ON THE SPIKE SIDE - genstop.py's four numbers, reproduced by a")
    print("    rebuilt path that was never shown them")
    print(f"{'feed':22s} {'stop':>5s} {'':>6s} {'p(stop)':>8s} {'mean slip R':>12s} "
          f"{'p90':>8s} {'max':>9s} {'>0.5R':>7s} {'n':>7s}")
    targets = {"boom_500_index": {5.0: 13.961, 10.0: 6.807, 25.0: 2.439, 50.0: 1.019}}
    for feed, f in real.items():
        for sd_ in STOPS:
            D = sd_ * f["spread"]
            rowr = slippage(f["_mid"], D, D, -f["side"], len(f["_mid"]))
            if rowr:
                print(f"{feed:22s} {sd_:5.0f} {'feed':>6s} {rowr['p_stop']:8.4f} "
                      f"{rowr['mean_slip_R']:12.3f} {rowr['p90_slip_R']:8.2f} "
                      f"{rowr['max_slip_R']:9.2f} {rowr['frac_over_half_R']:7.3f} "
                      f"{rowr['n']:7d}")
            for tag in ("spec", "closed", "pool"):
                rows = slippage(sims[feed][tag][0]["bars"]["ticks"], D, D, -f["side"],
                                SLIP_TICKS)
                if not rows or not rowr:
                    continue
                print(f"{'':22s} {'':5s} {tag:>6s} {rows['p_stop']:8.4f} "
                      f"{rows['mean_slip_R']:12.3f} {rows['p90_slip_R']:8.2f} "
                      f"{rows['max_slip_R']:9.2f} {rows['frac_over_half_R']:7.3f} "
                      f"{rows['n']:7d}")
                err = rows["mean_slip_R"] / rowr["mean_slip_R"] - 1.0
                ledger.append({"test": f"[{tag}] slippage multiple within 20% of the feed",
                               "feed": f"{feed}@{sd_:.0f}", "value": err,
                               "fired": abs(err) > 0.20})
                if feed in targets:
                    t = targets[feed][sd_]
                    e2 = rows["mean_slip_R"] / t - 1.0
                    ledger.append({"test": f"[{tag}] reproduces genstop.py's boom_500 numbers",
                                   "feed": f"{sd_:.0f} spreads", "value": e2,
                                   "fired": abs(e2) > 0.20})
                payload.setdefault("slippage", {}).setdefault(feed, {}).setdefault(
                    tag, {})[str(sd_)] = {"feed": rowr, "sim": rows}

    print("\n[6] THE BAR-LEVEL BATTERY - sixty days of one-minute bars, rebuilt")
    print("    The distributional test is on the one-minute change in *price*, not in the")
    print("    log: this generator is additive in price by construction, and a log return")
    print("    on a series whose level wanders carries the level as well as the law.")
    print(f"{'feed':22s} {'build':>6s} {'ann vol':>9s} {'feed':>9s} {'kurt':>10s} "
          f"{'feed':>10s} {'VR q10':>8s} {'drift z':>8s} {'KS D (1m)':>10s} {'p':>8s} {'n*':>11s}")
    for feed, f in real.items():
        rr = np.diff(f["_bars"]["close"])
        for tag in ("spec", "closed", "pool"):
            runs = sims[feed][tag]
            av = G.spread_across([r["ann"] for r in runs])
            ku = G.spread_across([r["kurt"] for r in runs])
            r2 = np.diff(runs[0]["bars"]["close"])
            k = G.ks2(rr, r2, rng=rng)
            dz = float(runs[0]["drift_z"])
            print(f"{feed:22s} {tag:>6s} {av['mean']:9.3f} "
                  f"{G.ann_vol(G.logrets(f['_bars']['close'], f['_bars']['ts'])):9.3f} "
                  f"{ku['mean']:10.2f} {G.kurtosis(rr):10.2f} "
                  f"{runs[0]['vr10']:8.4f} {dz:+8.2f} {k['D']:10.5f} "
                  f"{k['p']:8.4f} {G.nstar(k['D']):11.3g}")
            payload.setdefault("bars", {}).setdefault(feed, {})[tag] = {
                "ann": av, "kurt": ku, "ks": k, "nstar": G.nstar(k["D"])}
            ledger.append({"test": f"[{tag}] KS on the 1m price change does not reject",
                           "feed": feed, "value": k["p"], "fired": k["reject"]})
            kt = G.ks2(np.diff(f["_mid"]), np.diff(runs[0]["bars"]["ticks"]), rng=rng)
            print(f"{'':22s} {'':>6s} {'':>9s} {'':>9s} {'':>10s} {'':>10s} {'':>8s} "
                  f"{'':>8s} {kt['D']:10.5f} {kt['p']:8.4f} {G.nstar(kt['D']):11.3g}"
                  f"   <- tick moves")
            ledger.append({"test": f"[{tag}] KS on the tick move does not reject",
                           "feed": feed, "value": kt["p"], "fired": kt["reject"]})
            payload.setdefault("bars", {}).setdefault(feed, {})[tag + "_tick"] = {
                "ks": kt, "nstar": G.nstar(kt["D"])}
        # The two floors this comparison has to be read against: the feed's own
        # first thirty days against its last thirty, and one rebuild seed against
        # another at the same size. A jump process's bar distribution is carried
        # by a few hundred spikes, so neither floor is small.
        h = rr.size // 2
        kself = G.ks2(rr[:h], rr[h:], rng=rng)
        s0 = np.diff(sims[feed]["pool"][0]["bars"]["close"])
        kmc = G.ks2(s0[: s0.size // 2], s0[s0.size // 2:], rng=rng)
        print(f"{'':22s} {'floors':>6s} feed-vs-feed D {kself['D']:.5f} p {kself['p']:.4f}"
              f"   rebuild-vs-rebuild D {kmc['D']:.5f} p {kmc['p']:.4f}")
        payload.setdefault("bars", {}).setdefault(feed, {})["floors"] = {
            "feed_vs_feed": kself, "mc_vs_mc": kmc}

    print("\n[7] THE CONTROLS")
    vb = G.real_bars("volatility_75_index")
    vt = G.real_ticks("volatility_75_index")
    vgrid = G.quote_grid(vt["mid"])
    vsim = G.bars_from_stream(
        G.gen_gbm(1_000_000, 75.0, 2.0, float(vb["close"][0]), vgrid,
                  np.random.default_rng(SEEDS[0] + 5)), 30, 33_000, keep_ticks=1_000_000)
    dv = detect(vsim["ticks"])
    dr = detect(vt["mid"])
    print(f"    the same 10x detector on a *rebuilt* volatility_75_index: "
          f"{dv.get('n_spikes', 0)} spikes in {vsim['ticks'].size} ticks   (must be 0)")
    print(f"    and on the real volatility_75_index:                      "
          f"{dr.get('n_spikes', 0)} spikes in {vt['n']} ticks   (must be 0)")
    ledger.append({"test": "VOID if the detector finds spikes on a rebuilt GBM feed",
                   "feed": "volatility_75_index", "value": float(dv.get("n_spikes", 0)),
                   "fired": dv.get("n_spikes", 0) > 0})

    f = real.get("boom_500_index")
    if f:
        print("\n    the positive control on the rate test - a ladder of wrong lambdas,")
        print("    scored against the feed's own Poisson error on its 24 hours of ticks:")
        n_bars = min(f["_bars"]["n"] * BMULT, 260_000)
        pse = f["ticks_per_spike"] / math.sqrt(f["n_spikes"])
        print(f"      the feed: {f['ticks_per_spike']:.1f} ticks/spike +- {pse:.1f} "
              f"(Poisson on {f['n_spikes']} spikes)")
        caught = {}
        for mult in (0.90, 0.75, 0.50):
            f["tag"] = f"boom_500_index/lambda{mult}"
            bb = build(f, f["grid"], f["p0"], n_bars, SEEDS[0] + 77, True, lam_mult=mult)
            d2 = detect(bb["ticks"])
            seen = abs(d2["ticks_per_spike"] - f["ticks_per_spike"]) > 2 * pse
            caught[mult] = seen
            print(f"      lambda x{mult:.2f}: rebuilt {d2['ticks_per_spike']:8.1f} "
                  f"ticks/spike -> {'SEEN' if seen else 'missed'}")
        own = G.spread_across([r["fit"]["ticks_per_spike"]
                               for r in sims["boom_500_index"]["pool"]])
        print(f"      the honest rebuild's own {len(SEEDS)}-seed spread: "
              f"mean {own['mean']:.1f} sd {own['sd']:.2f} - the Monte Carlo is "
              f"{pse / max(own['sd'], 1e-9):.0f}x sharper than the feed")
        print("      so the feed's own sample is the limit, not the rebuild: a lambda")
        print("      error smaller than the ladder's first SEEN rung is undetectable here.")
        ledger.append({"test": "VOID unless lambda off by 50% is caught",
                       "feed": "boom_500_index", "value": 0.5,
                       "fired": not caught[0.50]})

    print("\n[8] THE FAILURE LEDGER")
    by: dict[str, list] = {}
    for e in ledger:
        by.setdefault(e["test"], []).append(e)
    print(f"{'condition':60s} {'cells':>6s} {'fired':>6s} {'worst cell':>34s}")
    nf = 0
    for name, es in sorted(by.items()):
        f2 = [e for e in es if e["fired"]]
        nf += len(f2)
        worst = max(es, key=lambda e: abs(e.get("value") or 0))
        print(f"{name:60s} {len(es):6d} {len(f2):6d} "
              f"{worst['feed'] + ' ' + format(worst['value'], '.5g'):>34s}")
    print(f"\n    {len(ledger)} pre-registered comparisons, {nf} fired.")
    for tag, what in (("spec", "the fitted five numbers"),
                      ("closed", "the same with E[J] := lambda*E[g]"),
                      ("pool", "empirical marginals")):
        f_ = sum(1 for e in ledger if e["fired"] and e["test"].startswith(f"[{tag}]"))
        n_ = sum(1 for e in ledger if e["test"].startswith(f"[{tag}]"))
        print(f"    of those: `{tag}` ({what}) {f_}/{n_}")
    payload["ledger"] = ledger

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        json.dump(json.loads(json.dumps(payload, default=float)), fh, indent=1)
    print(f"\nwrote {OUT}")


