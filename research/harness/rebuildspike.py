"""Rebuild Boom and Crash from the compound Poisson specification, and ask
whether the five published numbers are enough.

`deriving.md` section five writes the generator down completely:

    dP = -g  with probability 1 - 1/lambda,    +J  with probability 1/lambda

and tabulates, per feed, `lambda`, `E[g]`, `CV[g]`, `E[J]` and `median J`. Five
numbers. This harness builds two rebuilds and the difference between them is the
whole question:

* **closed** - the same, with `E[J]` replaced by `lambda * E[g]`, which is what
  the closure requires. `rebuildpaper.py` found the *published* triple misses its
  own closure by 6-12% on all six feeds, so a path built from both means as given
  is not a martingale; this asks whether the same is true of the triple fitted
  here, and it is the build to prefer if it wins.
* **spec** - the five published numbers alone. The grind is a gamma of the
  stated mean and coefficient of variation; the jump is a lognormal matched to
  the stated mean *and* median, which is exactly the shape information the table
  carries. Nothing else is used.
* **pool** - the same arrival process with the grind and jump magnitudes
  resampled from the feed's own 24 hours of ticks. This is the same mechanism
  with the marginals handed to it, and it bounds how much of any disagreement is
  the mechanism and how much is the two-parameter marginal.

If `spec` matches the feed and `pool` does no better, the published table
re-instantiates the instrument and `deriving.md` is complete for this family. If
`pool` matches and `spec` does not, the mechanism is right and the published
marginal is not sufficient - which is a precise and useful failure.

The closure `E[J] = lambda * E[g]` is **not imposed**. The two published means
are used as given, so whether the rebuilt path comes out a martingale is a
result rather than a construction.

## What would count as failure, written before any number was looked at

1. **The rate fails** if the rebuilt ticks-per-spike, recovered by the same 10x
   median-move detector the feed was measured with, misses the feed's
   (267.7, 529.4, 908.3, 329.0, 507.7, 973.8) by more than the Poisson error on
   the real counts - 86 to 306 spikes, so 6% to 11% - or if the rebuilt family
   does not order 300 < 500 < 1000 in ticks per spike on both Boom and Crash.
2. **The closure fails** if `(1-p)E[g] - pE[J]` on the rebuilt path is more than
   2 of the **feed's** standard errors from zero on more than one of the six.
   The real feeds run |z| <= 1.21 on their own 24 hours of ticks.
3. **The grind fails** if the recovered per-tick grind CV is outside
   **0.63-0.68**, the band `generators.md` measured across all six.
4. **The P&L law fails** if the rebuilt distribution of an N-tick hold on the
   grind side misses the real one on mean, median, sd, P(profit) or the 1st and
   99th percentiles by more than `derivejump.py`'s own agreement, at any
   N in {10, 100, 500, 3000}.
5. **The stop arithmetic fails** if the rebuilt slippage multiple misses
   `genstop.py`'s **+13.96R, +6.81R, +2.44R, +1.02R** on `boom_500_index` by
   more than 20% - the same bar `derivejump.py` set itself, on numbers measured
   before either page existed.
6. **The waiting time fails** if the rebuilt spike-gap CV is outside 0.85-1.15.
   The distributional tests are run on the one-minute change in **price**, not
   on the log return: this generator is additive in price by construction and a
   log return on a series whose level wanders carries the level as well as the
   law.
7. **The run is void** if the control fires: the same detector run over a
   rebuilt `volatility_75_index` must find **zero** spikes at 10x, and the real
   one does.
8. **The run is void** if a statistic lands on exactly its null - a closure of
   exactly 0.000000 would mean the closure had been imposed somewhere.


## Amended before the real data was touched, and why

Every harness here was first run end to end against a **synthetic** database -
sixty days of bars and twenty-four hours of ticks for all twenty-six feeds,
generated by these same generators - so that a crash or a broken test would
surface on data whose truth was known rather than on the lab. Three conditions
were rewritten during that dry run. Each amendment is recorded here rather than
quietly applied, because a failure condition edited after seeing the answer is
not a failure condition, and the only defence is to say exactly when it was
edited and what forced it.

* **The closure tolerance** was written against the *rebuild's* standard error.
  The rebuild carries sixty times the feed's ticks, so its own standard error is
  eight times smaller and a drift the feed cannot see would have failed the
  test. Scored at the feed's resolution instead, which is the comparison that
  means something.
* **The lambda control** was a single rung at 10%. On the dry run a 10% error in
  lambda fell *inside* two Poisson standard errors of the feed's own estimate on
  86 to 306 spikes, so it cannot be caught and requiring it to be caught would
  have voided a sound run. It is now a ladder - 10%, 25%, 50% - with the VOID
  condition on the 50% rung and the others reported as the resolution the feed's
  own sample supports.

## The controls

* **`volatility_75_index`, rebuilt**, through the identical spike detector.
* **lambda off by 10%**, as the positive control on the rate test: if a rebuild
  that spikes 10% too often is not caught, the rate test proves nothing.
* **across seeds**, with the spread reported beside the real feed's own
  standard error - which on 86 to 306 spikes is large, and is the reason the
  rate test has the tolerance it does.
"""

