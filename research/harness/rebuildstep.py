"""Rebuild Step Index and Range Break, and find out what the specification is
missing.

These two are the lattice families: both move one fixed unit a tick, both print
once a second, and both are described in `deriving.md` - but described to very
different depths, which is the point of putting them on one page.

**Step Index is fully specified.** A fixed 0.1 increment, a fair coin, a spread
of exactly one step, one tick a second. Four numbers, and the rebuild gets
nothing else. Section three of `deriving.md` then says the whole instrument is
gambler's ruin: `P(target) = S/(S+T)`, `E[tau] = S*T` steps, and `(S+d)/(S+T+2d)`
when the fill triggers one step past the level.

**Range Break is not.** `deriving.md` publishes the break rate - memoryless at
86.5 and 178.8 minutes - and measures the consequence: dropping the bars that
contain a break leaves a process that is **sub-diffusive by 3.6x and 8.9x**,
while the all-bars variance ratio stays flat over three orders of magnitude in
horizon. It says in as many words that the range rule itself is unknown: "how
wide, how it resets, what counts as a bounce". So a rebuild needs two parameters
that are not in the specification, and the honest experiment is to estimate them
from something *other* than the variance-ratio curve and then predict that curve.

The mechanism proposed here is the simplest one that could produce both facts at
once: a `+-1` walk that **bounces** off both edges of a range of fixed width, and
a memoryless break that jumps the price and opens a new range where it lands.
Two candidate re-range rules are built and both are reported, because
`deriving.md` publishes neither and they are different generators:

* `edge` - the break point becomes the new range's near edge, so the price has
  the whole range in front of it;
* `edge_far` - the break overshoots and the new range opens behind it, so the
  price starts at the far edge and the next move is back into the range;
* `centre` - the new range is centred on the break point.

The band width is estimated from the *visited* range between breaks and the jump
by measuring break bars directly; the six variance ratios at
n = 1, 5, 20, 100, 500, 1000 are then out-of-sample.

## What would count as failure, written before any number was looked at

1. **Step fails** if the rebuilt tick-magnitude concentration is below 99.99% on
   a single value, where the feed reads **99.9988%**.
2. **Step fails** if `p(up)` recovered from the rebuild is more than 3 SE from
   the 0.5 that went in, or if more than 2 of the 30 sign autocorrelations
   exceed `+-3/sqrt(n)` (1.5 expected), or if `|runs z| > 3`.
3. **Step fails** if the rebuilt gambler's-ruin hit rates and durations miss
   `S/(S+T)` and `S*T` by more than the real feed misses them - which
   `deriving.md` puts at 0.03-0.07 standard errors on `P` and -2.2% to +6.9% on
   `E[tau]`.
4. **Step fails** if a chi-square on the one-minute change distribution - a sum
   of sixty coin flips, 61 atoms, not a continuum - rejects real against
   rebuilt at alpha = 0.05.
5. **Range Break fails** if the rebuilt all-bars variance ratio is not flat.
   Flat is defined here, in advance, as `max/min <= 1.35` over
   n in {1,5,20,100,500,1000}: the real RB100 gives 4.713/4.217 = **1.118** and
   RB200 5.917/5.176 = **1.143**, and the n=1000 cell carries a 15% standard
   error of its own, so anything past 1.35 is a real shape difference.
6. **Range Break fails** if the feed's own ex-break variance ratio sits more
   than **3 standard deviations** from the middle of a `NULL_SEEDS`-seed rebuild
   ensemble simulated at the feed's own sample size, at any
   n in {1, 5, 20, 100, 500, 1000}. The curve to reproduce runs from ~1.0 at
   n=1 to the feed's **0.283** (RB100) and **0.112** (RB200) at n >= 100.
7. **Range Break fails** if the break waiting-time CV is outside 0.85-1.15
   (real: 1.003 and 1.075) or the RB100/RB200 break-rate ratio is outside
   2.066 +- 0.30 (the real 95% CI is [1.86, 2.30]).
8. **The run is void** if flatness is achieved degenerately - a price that does
   not move between breaks, or a break in more than one bar in ten. Both are
   checked and printed.
9. **The run is void** if a statistic lands on exactly its null, or if the
   positive control fails: a rebuild with `p_up = 0.501` instead of 0.5, and one
   with the range switched off entirely, must both be caught by this battery.


## Amended before the real data was touched, and why

Every harness here was first run end to end against a **synthetic** database -
sixty days of bars and twenty-four hours of ticks for all twenty-six feeds,
generated by these same generators - so that a crash or a broken test would
surface on data whose truth was known rather than on the lab. Three conditions
were rewritten during that dry run. Each amendment is recorded here rather than
quietly applied, because a failure condition edited after seeing the answer is
not a failure condition, and the only defence is to say exactly when it was
edited and what forced it.

* **The Range Break tolerance in condition 6** was written as "within 2 standard
  errors", with the standard error taken as `sqrt(2/k)` on `k` non-overlapping
  windows. On the dry run that test rejected the *true* parameters at up to
  **4.6 standard errors** on data this very generator had produced. The Gaussian
  standard error is simply wrong for a variance ratio on a jump process, so it
  was replaced by a Monte Carlo null: the feed is scored against an ensemble of
  rebuilds at the feed's own sample size, at 3 ensemble standard deviations.
  The tolerance got *looser* and that is the honest direction to note, but the
  estimator got right, which is the reason.
* **The `edge` rule was added during the dry run**, against `deriving.md`'s
  *published* ex-break curve rather than against any measurement of my own. A
  centred range needs a band of 132 steps to carry the plateau at n >= 100, and
  a band that wide relaxes in 3,500 ticks against a 5,190-tick break interval,
  so it cannot also be confined at n = 20. Anchoring the new range on the break
  point quadruples the displacement accumulated inside a range at the same
  width, which lets the band be half as wide and relax three times faster. Both
  rules are built and both are reported; nothing was dropped.
* **The band width is fitted on the visited range**, and the dry run showed the
  median alone cannot do it: that distribution has an atom at the band width, so
  a one-step error moves half the mass and leaves the median where it was. The
  fit now bisects on the median and then minimises the KS distance to the
  measured visited-range distribution over a seven-step bracket. It still never
  sees a variance ratio.

## The controls

* **the feed against itself**, first half against last half, through the same
  tests.
* **a free walk with no range at all**, which must produce an ex-break curve
  flat at 1.0 - if it does not, the sub-diffusion estimator is broken and the
  Range Break result cannot be read.
* **`p_up = 0.501`**, a bias of 23 standard errors on the 60-day bar sample,
  which the fair-coin test must see.
"""

