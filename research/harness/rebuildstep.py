    print(f"{'seed':>10s} {'bars':>9s} {'concentration':>14s} {'p_up':>10s} {'z':>7s} "
          f"{'runs z':>8s} {'acf>band':>9s} {'ann vol':>9s}")
    sruns = []
    for sd in SEEDS:
        bb = sim_step(min(rb["n"] * MULT, 900_000), 0.5, sd, float(rb["close"][0]))
        m2 = magnitude_concentration(bb["ticks"])
        c2 = coin(bb["ticks"])
        r2 = G.logrets(bb["close"], bb["ts"])
        sruns.append({"bars": bb, "mc": m2, "coin": c2, "ann": G.ann_vol(r2)})
        print(f"{sd:>10d} {bb['n']:9d} {m2['share']:14.6%} {c2['p_up']:10.6f} "
              f"{c2['z']:+7.2f} {c2['runs_z']:+8.3f} {c2['n_outside']:9d} "
              f"{G.ann_vol(r2):9.3f}", flush=True)
    conc = G.spread_across([r["mc"]["share"] for r in sruns])
    ledger.append({"test": "Step concentration >= 99.99% on one magnitude", "feed": "step_index",
                   "value": conc["mean"], "fired": conc["mean"] < 0.9999})
    zs = G.spread_across([r["coin"]["z"] for r in sruns])
    ledger.append({"test": "Step recovered p(up) within 3 SE of the 0.5 put in",
                   "feed": "step_index", "value": zs["mean"], "fired": abs(zs["mean"]) > 3})
    ob = G.spread_across([float(r["coin"]["n_outside"]) for r in sruns])
    ledger.append({"test": "Step sign acf: at most 2 of 30 lags outside the band",
                   "feed": "step_index", "value": ob["mean"], "fired": ob["mean"] > 2})
    rz = G.spread_across([r["coin"]["runs_z"] for r in sruns])
    ledger.append({"test": "Step |runs z| <= 3", "feed": "step_index", "value": rz["mean"],
                   "fired": abs(rz["mean"]) > 3})
    print(f"    real concentration {mc['share']:.6%}  rebuilt {conc['mean']:.6%} "
          f"(sd {conc['sd']:.2e} over {len(SEEDS)} seeds)")

    print("\n[3] STEP INDEX - gambler's ruin off the rebuilt path against the closed form")
    print(f"{'S:T':>7s} {'':>4s} {'n':>7s} {'P(hit)':>9s} {'derived':>9s} {'z':>7s} "
          f"{'E[tau]':>9s} {'S*T':>7s} {'err':>8s}")
    ru_real = ruin(rt["mid"], step)
    ru_sim = ruin(sruns[0]["bars"]["ticks"], STEP_SIZE)
    for tag, rows in (("real", ru_real), ("sim", ru_sim)):
        for r2 in rows:
            z = (r2["p"] - r2["p_theory"]) / r2["se_p"]
            print(f"{r2['S']}:{r2['T']:<5d} {tag:>4s} {r2['n']:7d} {r2['p']:9.4f} "
                  f"{r2['p_theory']:9.4f} {z:+7.2f} {r2['etau']:9.2f} {r2['etau_theory']:7.0f} "
                  f"{100 * (r2['etau'] / r2['etau_theory'] - 1):7.2f}%")
            if tag == "sim":
                ledger.append({"test": "Step rebuilt hit rate within 3 SE of S/(S+T)",
                               "feed": f"{r2['S']}:{r2['T']}", "value": z,
                               "fired": abs(z) > 3})
    ru_past = ruin(sruns[0]["bars"]["ticks"], STEP_SIZE, past=True)
    print("    the fill-one-step-past convention, which `deriving.md` shows is what")
    print("    `generators.md` actually measured:")
    for r2 in ru_past:
        print(f"      {r2['S']}:{r2['T']:<4d} rebuilt {r2['p']:.4f}  "
              f"derived (S+d)/(S+T+2d) {r2['p_theory']:.4f}")

    print("\n[4] STEP INDEX - the one-minute change distribution, sixty coin flips")
    chg_s = np.diff(sruns[0]["bars"]["close"])
    c2t = G.chi2_hist(chg_r, chg_s, nbin=40)
    kk = G.ks2(chg_r, chg_s, rng=rng)
    h = chg_r.size // 2
    kc = G.ks2(chg_r[:h], chg_r[h:], rng=rng)
    print(f"    real n={chg_r.size}  rebuilt n={chg_s.size}")
    print(f"    chi-square p {c2t['p']:.4f} (df {c2t['df']})   KS D {kk['D']:.5f} "
          f"crit {kk['D_crit_05']:.5f} p {kk['p']:.4f}   n* {G.nstar(kk['D']):.3g}")
    print(f"    control, real first half against real last half: D {kc['D']:.5f} "
          f"p {kc['p']:.4f}")
    ledger.append({"test": "Step 1m change distribution: chi-square does not reject",
                   "feed": "step_index", "value": c2t["p"], "fired": bool(c2t["reject"])})

    print("\n[5] STEP INDEX - the positive control, p_up = 0.501")
    bb = sim_step(rb["n"], 0.501, SEEDS[0] + 99, float(rb["close"][0]))
    cbad = coin(bb["ticks"])
    chg_b = np.diff(bb["close"])
    mb = float(chg_b.mean())
    seb = float(chg_b.std(ddof=1) / math.sqrt(chg_b.size))
    print(f"    tick p(up) {cbad['p_up']:.6f} z {cbad['z']:+.2f}  |  bar-sample implied "
          f"p(up) {0.5 + mb / (2 * STEP_SIZE * TPB):.6f}, z on the mean change {mb / seb:+.2f}")
    zg = float(chg_s.mean() / (chg_s.std(ddof=1) / math.sqrt(chg_s.size)))
    print(f"    the same bar test on the honest rebuild: {zg:+.2f}")
    ledger.append({"test": "VOID unless p_up=0.501 is caught on the bar sample",
                   "feed": "step_index", "value": mb / seb, "fired": abs(mb / seb) < 3})
    print("    and the sample size a fair-coin test needs to see the feed's own")
    print(f"    measured bias of 0.000266: n* = {0.25 * (1.96 / 0.000266) ** 2:.3g} flips")

    payload["step"] = {"real": {"concentration": mc["share"], "p_up": cn["p_up"],
                                "se": cn["se"], "runs_z": cn["runs_z"],
                                "spread_in_steps": spread_med / step},
                       "sim_concentration": conc, "sim_p_up_z": zs,
                       "ruin_real": ru_real, "ruin_sim": ru_sim, "ruin_past": ru_past,
                       "chi2": c2t, "ks": kk, "control": kc}

    # -------------------------------------------------------- range break -----
    print("\n[6] RANGE BREAK - reproducing `deriving.md`'s variance-ratio table first")
    print("    Three readings of 'ex-break'. Only one of them can produce a number at")
    print("    n=1000, because a thousand break-free minutes has probability 1e-5.")
    rbfeeds = ["range_break_100_index", "range_break_200_index"]
    rbreal, rbpar = {}, {}
    for feed in rbfeeds:
        bars = G.real_bars(feed)
        tk = G.real_ticks(feed)
        d = np.diff(tk["mid"])
        st = float(np.median(np.abs(d[d != 0])))
        cur = vr_curves(bars, st)
        bs = break_stats(bars, st)
        vis = visited_ranges(bars, st)
        rbreal[feed] = {"bars": bars, "ticks": tk, "step": st, "vr": cur, "brk": bs,
                        "visited": vis}
        print(f"\n    {feed}: step {st:g}, {tk['per_sec']:.4f} ticks/s, "
              f"{bs['n_breaks']} breaks in {bars['n']} bars = {bs['minutes_per_break']:.1f} "
              f"min/break, gap CV {bs['gap_cv']:.3f}")
        print(f"      break jump in steps: median {bs['jump_median']:.1f} "
              f"mean {bs['jump_mean']:.1f} sd {bs['jump_sd']:.1f} "
              f"q10/q90/q99 {bs['jump_q'].get(10, 0):.0f}/{bs['jump_q'].get(90, 0):.0f}/"
              f"{bs['jump_q'].get(99, 0):.0f}")
        print(f"      visited range between breaks, in steps: median "
              f"{np.median(vis):.1f}, q90 {np.percentile(vis, 90):.1f}, max {vis.max():.1f} "
              f"(n={vis.size})")
        print(f"      {'n':>6s} " + " ".join(f"{n:>9d}" for n in VR_N))
        for tag in ("all", "splice", "window"):
            print(f"      {tag:>6s} " + " ".join(
                f"{cur[tag].get(n, float('nan')):9.3f}" for n in VR_N))
        print(f"      {'+-SE':>6s} " + " ".join(f"{cur['se'][n]:9.3f}" for n in VR_N))
        print("      window cell counts: " + " ".join(
            f"n={n}:{cur['window'].get(f'{n}_n', 0)}" for n in VR_N))
        print("      break share of variance: " + ", ".join(
            f"n={k}: {v:.3f}" for k, v in cur["break_share"].items()))

    # a free walk with no range at all: the estimator's own control
    print("\n    control - a free +-1 walk with no range and no break:")
    ctlbars = G.bars_from_stream(
        G.gen_step(400_000 * TPB, 1.0, 0.5, 10000.0, np.random.default_rng(5)),
        TPB, 400_000)
    cc = vr_curves(ctlbars, 1.0)
    print(f"      {'n':>6s} " + " ".join(f"{n:>9d}" for n in VR_N))
    for tag in ("all", "splice"):
        print(f"      {tag:>6s} " + " ".join(
            f"{cc[tag].get(n, float('nan')):9.3f}" for n in VR_N))
    ledger.append({"test": "VOID unless the free-walk control reads 1.0 at every n",
                   "feed": "free walk",
                   "value": max(abs(cc["all"][n] - 1.0) for n in VR_N),
                   "fired": max(abs(cc["all"][n] - 1.0) for n in VR_N) > 0.15})

    print("\n[7] RANGE BREAK REBUILT - the band width estimated off the *visited* range,")
    print("    never off the variance ratio, and then the six variance ratios predicted.")
    print("    Two candidate re-range rules, because `deriving.md` publishes neither:")
    print("      edge   - the break point becomes the new range's near edge")
    print("      centre - the new range is centred on the break point")
    for feed in rbfeeds:
        R = rbreal[feed]
        mbt = R["brk"]["minutes_per_break"] * TPB
        pool = R["brk"]["_jump"]
        rbpar[feed] = {"mean_break_ticks": mbt,
                       "target_median": float(np.median(R["visited"]))}
        for anchor in ANCHORS:
            band, got, dks = fit_band(R["visited"], mbt, pool,
                                      float(R["bars"]["close"][0]), R["step"], SEEDS[0],
                                      anchor=anchor)
            rbpar[feed][anchor] = {"band": band, "fit_median": got, "fit_ks_D": dks}
            print(f"    {feed} [{anchor}]: band {band} steps (median visited range "
                  f"{got:.1f} against the feed's {np.median(R['visited']):.1f}, "
                  f"KS D {dks:.3f}); break every {mbt:.0f} ticks; jump resampled from "
                  f"{pool.size} break bars")

    print(f"\n{'feed':22s} {'rule':>7s} {'seed':>10s} {'':>7s} "
          + " ".join(f"{'n=' + str(n):>9s}" for n in VR_N) + f" {'flat max/min':>13s}")
    rbsim, rbnull = {}, {}
    for feed in rbfeeds:
        R = rbreal[feed]
        rbsim[feed] = {}
        rbnull[feed] = {}
        n_bars = min(R["bars"]["n"] * RBMULT, 500_000)
        for anchor in ANCHORS:
            band = rbpar[feed][anchor]["band"]
            runs = []
            for sd in SEEDS:
                bb = sim_rb(n_bars, band, rbpar[feed]["mean_break_ticks"],
                            R["brk"]["_jump"], sd, float(R["bars"]["close"][0]),
                            R["step"], anchor)
                cur = vr_curves(bb, R["step"])
                bs = break_stats(bb, R["step"])
                runs.append({"vr": cur, "brk": bs, "bars": bb})
                allv = [cur["all"][n] for n in VR_N]
                print(f"{feed:22s} {anchor:>7s} {sd:>10d} {'all':>7s} "
                      + " ".join(f"{v:9.3f}" for v in allv)
                      + f" {max(allv) / min(allv):13.3f}", flush=True)
                print(f"{'':22s} {'':>7s} {'':>10s} {'splice':>7s} " + " ".join(
                    f"{cur['splice'][n]:9.3f}" for n in VR_N))
            rbsim[feed][anchor] = runs
            # The sampling distribution of a variance ratio on a jump process is
            # nothing like sqrt(2/k) - the smoke test on data generated by this
            # very model put the true parameters 4.6 "standard errors" away. So
            # the null is built by Monte Carlo at the *feed's own sample size*
            # instead, and the feed is scored against that ensemble.
            null = []
            for j in range(NULL_SEEDS):
                bb = sim_rb(R["bars"]["n"], band, rbpar[feed]["mean_break_ticks"],
                            R["brk"]["_jump"], 7000 + 13 * j, float(R["bars"]["close"][0]),
                            R["step"], anchor)
                null.append(vr_curves(bb, R["step"]))
            rbnull[feed][anchor] = null
            fl = G.spread_across([max(r["vr"]["all"][n] for n in VR_N)
                                  / min(r["vr"]["all"][n] for n in VR_N) for r in runs])
            ledger.append({"test": f"[{anchor}] RB all-bars variance ratio flat (max/min <= 1.35)",
                           "feed": feed, "value": fl["mean"], "fired": fl["mean"] > 1.35})
            for n in VR_N:
                sp = G.spread_across([c["splice"][n] for c in null])
                tgt = R["vr"]["splice"][n]
                z = (tgt - sp["mean"]) / sp["sd"] if sp["sd"] else float("nan")
                ledger.append({
                    "test": f"[{anchor}] RB ex-break variance ratio at n={n} within 3 MC SD",
                    "feed": feed, "value": z, "fired": abs(z) > 3})
            cvs = G.spread_across([r["brk"]["gap_cv"] for r in runs])
            ledger.append({"test": f"[{anchor}] RB break waiting-time CV in 0.85-1.15",
                           "feed": feed, "value": cvs["mean"],
                           "fired": not (0.85 <= cvs["mean"] <= 1.15)})
            lvl = G.spread_across([r["brk"]["n_breaks"] / r["bars"]["n"] for r in runs])
            ledger.append({"test": f"[{anchor}] VOID if more than one bar in ten has a break",
                           "feed": feed, "value": lvl["mean"], "fired": lvl["mean"] > 0.1})
        allr = [R["vr"]["all"][n] for n in VR_N]
        print(f"{feed:22s} {'FEED':>7s} {'':>10s} {'all':>7s} "
              + " ".join(f"{v:9.3f}" for v in allr)
              + f" {max(allr) / min(allr):13.3f}")
        print(f"{'':22s} {'':>7s} {'':>10s} {'splice':>7s} " + " ".join(
            f"{R['vr']['splice'][n]:9.3f}" for n in VR_N))

    print(f"\n    the feed scored against a {NULL_SEEDS}-seed rebuild ensemble at the")
    print("    feed's own sample size: (feed - ensemble mean) / ensemble sd.")
    print(f"{'feed':22s} {'rule':>7s} {'series':>7s} "
          + " ".join(f"{'n=' + str(n):>9s}" for n in VR_N))
    for feed in rbfeeds:
        R = rbreal[feed]
        for anchor in ANCHORS:
            null = rbnull[feed][anchor]
            for series in ("all", "splice"):
                row = []
                for n in VR_N:
                    sp = G.spread_across([c[series][n] for c in null])
                    row.append((R["vr"][series][n] - sp["mean"]) / sp["sd"]
                               if sp["sd"] else float("nan"))
                print(f"{feed:22s} {anchor:>7s} {series:>7s} "
                      + " ".join(f"{v:+9.2f}" for v in row))
    print("\n    and the ensemble's own spread, which is what those z are divided by:")
    print(f"{'feed':22s} {'rule':>7s} {'series':>7s} "
          + " ".join(f"{'n=' + str(n):>9s}" for n in VR_N))
    for feed in rbfeeds:
        for anchor in ANCHORS:
            null = rbnull[feed][anchor]
            for series in ("all", "splice"):
                print(f"{feed:22s} {anchor:>7s} {series:>7s} " + " ".join(
                    f"{G.spread_across([c[series][n] for c in null])['sd']:9.4f}"
                    for n in VR_N))

    print("\n[8] RANGE BREAK - the levels the flatness is made of, so it cannot be degenerate")
    print(f"{'feed':24s} {'':>8s} {'min/break':>10s} {'gap CV':>8s} {'ex-brk 1m sd':>13s} "
          f"{'jump median':>12s} {'bars w/ break':>14s}")
    for feed in rbfeeds:
        R = rbreal[feed]
        chg = np.diff(R["bars"]["close"])
        brk = break_bars(R["bars"], R["step"])[1:]
        print(f"{feed:24s} {'feed':>8s} {R['brk']['minutes_per_break']:10.1f} "
              f"{R['brk']['gap_cv']:8.3f} {chg[~brk].std(ddof=1) / R['step']:13.2f} "
              f"{R['brk']['jump_median']:12.1f} "
              f"{R['brk']['n_breaks'] / R['bars']['n']:14.5f}")
        for r2 in rbsim[feed][MAIN_ANCHOR][:1]:
            ch2 = np.diff(r2["bars"]["close"])
            b2 = break_bars(r2["bars"], R["step"])[1:]
            print(f"{'':24s} {'rebuilt':>8s} {r2['brk']['minutes_per_break']:10.1f} "
                  f"{r2['brk']['gap_cv']:8.3f} {ch2[~b2].std(ddof=1) / R['step']:13.2f} "
                  f"{r2['brk']['jump_median']:12.1f} "
                  f"{r2['brk']['n_breaks'] / r2['bars']['n']:14.5f}")

    r100 = rbreal["range_break_100_index"]["brk"]["minutes_per_break"]
    r200 = rbreal["range_break_200_index"]["brk"]["minutes_per_break"]
    s100 = G.spread_across([r2["brk"]["minutes_per_break"]
                            for r2 in rbsim["range_break_100_index"][MAIN_ANCHOR]])["mean"]
    s200 = G.spread_across([r2["brk"]["minutes_per_break"]
                            for r2 in rbsim["range_break_200_index"][MAIN_ANCHOR]])["mean"]
    print(f"\n    RB200/RB100 break interval: feed {r200 / r100:.3f}  rebuilt {s200 / s100:.3f}"
          f"  documented 2.000, generators.md 2.066 [1.86, 2.30]")
    ledger.append({"test": "RB rate ratio 2.066 +- 0.30", "feed": "RB200/RB100",
                   "value": s200 / s100, "fired": abs(s200 / s100 - 2.066) > 0.30})

    print("\n[9] RANGE BREAK - the distributions, real against rebuilt")
    print(f"{'feed':24s} {'what':>16s} {'n real':>8s} {'n sim':>9s} {'KS D':>9s} "
          f"{'D crit':>8s} {'p':>8s} {'chi2 p':>8s} {'n*':>12s}")
    for feed in rbfeeds:
        R = rbreal[feed]
        S = rbsim[feed][MAIN_ANCHOR][0]
        exr = np.diff(R["bars"]["close"])[~break_bars(R["bars"], R["step"])[1:]] / R["step"]
        exs = np.diff(S["bars"]["close"])[~break_bars(S["bars"], R["step"])[1:]] / R["step"]
        for what, a, b in (("1m change", np.diff(R["bars"]["close"]) / R["step"],
                            np.diff(S["bars"]["close"]) / R["step"]),
                           ("ex-break 1m", exr, exs),
                           ("break gaps", np.diff(R["brk"]["_idx"]).astype(float),
                            np.diff(S["brk"]["_idx"]).astype(float)),
                           ("visited range", R["visited"], visited_ranges(S["bars"], R["step"]))):
            if a.size < 30 or b.size < 30:
                continue
            k = G.ks2(a, b, rng=rng)
            c2t = G.chi2_hist(a, b, nbin=30)
            print(f"{feed:24s} {what:>16s} {a.size:8d} {b.size:9d} {k['D']:9.5f} "
                  f"{k['D_crit_05']:8.5f} {k['p']:8.4f} {c2t['p']:8.4f} "
                  f"{G.nstar(k['D']):12.3g}")
            payload.setdefault("rb_ks", {}).setdefault(feed, {})[what] = {"ks": k, "chi2": c2t}
            ledger.append({"test": f"RB {what}: KS does not reject", "feed": feed,
                           "value": k["p"], "fired": k["reject"]})

    payload["rangebreak"] = json.loads(json.dumps(
        {f: {"params": rbpar[f],
             "real_vr": {k: v for k, v in rbreal[f]["vr"].items() if k != "break_share"},
             "real_break": {k: v for k, v in rbreal[f]["brk"].items() if not k.startswith("_")},
             "sim_vr_all": {a: [{n: r2["vr"]["all"][n] for n in VR_N} for r2 in rbsim[f][a]]
                            for a in ANCHORS},
             "sim_vr_splice": {a: [{n: r2["vr"]["splice"][n] for n in VR_N} for r2 in rbsim[f][a]]
                               for a in ANCHORS}}
         for f in rbfeeds}, default=float))

    print("\n[10] THE FAILURE LEDGER")
    by: dict[str, list] = {}
    for e in ledger:
        by.setdefault(e["test"], []).append(e)
    print(f"{'condition':62s} {'cells':>6s} {'fired':>6s} {'worst cell':>30s}")
    nf = 0
    for name, es in by.items():
        f2 = [e for e in es if e["fired"]]
        nf += len(f2)
        worst = max(es, key=lambda e: abs(e.get("value") or 0))
        print(f"{name:62s} {len(es):6d} {len(f2):6d} "
              f"{worst['feed'] + ' ' + format(worst['value'], '.5g'):>30s}")
    print(f"\n    {len(ledger)} pre-registered comparisons, {nf} fired.")
    payload["ledger"] = ledger

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        json.dump(json.loads(json.dumps(payload, default=float)), fh, indent=1)
    print(f"\nwrote {OUT}")


