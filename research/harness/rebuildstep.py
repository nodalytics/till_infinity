def score_against_published(feed: str, anchor: str, band: int, jump: float,
                            n_bars: int, seed: int) -> dict:
    """Simulate one candidate and score its variance-ratio curve against the
    published one, in absolute deviation on the ex-break series plus the
    flatness of the all-bars series."""
    tgt = PUBLISHED_VR[feed]
    mbt = tgt["minutes_per_break"] * TPB
    bb = sim_rb(n_bars, band, mbt, np.array([float(jump)]), seed, 5000.0, 1.0, anchor)
    cur = vr_curves(bb, 1.0)
    allv = [cur["all"][n] for n in VR_N]
    err = [cur["splice"][n] - tgt["splice"][n] for n in VR_N]
    return {"anchor": anchor, "band": band, "jump": jump,
            "all": allv, "splice": [cur["splice"][n] for n in VR_N],
            "err": err, "mae": float(np.mean(np.abs(err))),
            "flat": max(allv) / min(allv),
            "flat_target": max(tgt["all"].values()) / min(tgt["all"].values()),
            "all_level_err": float(np.mean(allv) - np.mean(list(tgt["all"].values())))}


def published_study(n_bars: int, seed: int) -> dict:
    """Scan the two unpublished parameters for each candidate rule, against the
    published curve. No database, no fitting to anything measured here."""
    out: dict[str, list] = {}
    print("\n[0] THE RANGE RULE, SCORED AGAINST `deriving.md`'s PUBLISHED CURVE")
    print("    Three candidate re-range rules and a scan of the two parameters the")
    print("    specification does not contain. Nothing here reads research.db: the")
    print("    published variance-ratio table is the measurement being matched.")
    for feed in PUBLISHED_VR:
        tgt = PUBLISHED_VR[feed]
        best: list = []
        for anchor in ANCHORS:
            grid = ((45, 60, 66, 75, 90, 110) if anchor != "centre"
                    else (110, 132, 160, 190))
            for band in grid:
                for jump in (120.0, 140.0, 160.0, 190.0, 230.0):
                    r = score_against_published(feed, anchor, band, jump, n_bars, seed)
                    # the all-bars level has to be right too, not just the shape
                    r["score"] = r["mae"] + abs(r["all_level_err"]) / 10.0
                    best.append(r)
        best.sort(key=lambda r: r["score"])
        out[feed] = best
        pub_flat = max(tgt["all"].values()) / min(tgt["all"].values())
        print(f"\n    {feed}: published all-bars flatness {pub_flat:.3f}, "
              f"break every {tgt['minutes_per_break']:.1f} minutes")
        print(f"      {'rule':9s} {'band':>5s} {'|J|':>5s} {'MAE':>7s} {'flat':>6s} "
              + " ".join(f"{'n=' + str(n):>8s}" for n in VR_N))
        print(f"      {'PUBLISHED':9s} {'':>5s} {'':>5s} {'':>7s} {pub_flat:6.3f} "
              + " ".join(f"{tgt['splice'][n]:8.3f}" for n in VR_N))
        for anchor in ANCHORS:
            r = next(x for x in best if x["anchor"] == anchor)
            print(f"      {anchor:9s} {r['band']:5d} {r['jump']:5.0f} {r['mae']:7.4f} "
                  f"{r['flat']:6.3f} " + " ".join(f"{v:8.3f}" for v in r["splice"]))
            print(f"      {'':9s} {'':5s} {'':5s} {'':7s} {'':6s} "
                  + " ".join(f"{v:+8.3f}" for v in r["err"]) + "   <- residual")
    return out


