# ------------------------------------------------------------ measurements --
def magnitude_concentration(mid: np.ndarray) -> dict:
    d = np.round(np.diff(mid), 10)
    nz = np.abs(d[d != 0])
    if not nz.size:
        return {}
    c = Counter(np.round(nz, 8))
    top = c.most_common(6)
    return {"n_moves": int(nz.size), "zero_moves": int((d == 0).sum()),
            "mode": float(top[0][0]), "share": top[0][1] / nz.size,
            "top": [(float(k), int(v), v / nz.size) for k, v in top]}


def coin(mid: np.ndarray) -> dict:
    d = np.diff(mid)
    s = np.sign(d)
    s = s[s != 0]
    n = s.size
    p = float((s > 0).mean())
    se = math.sqrt(0.25 / n)
    band = 3.0 / math.sqrt(n)
    acfs = {lag: G.acf(s, lag) for lag in range(1, 31)}
    return {"n": n, "p_up": p, "se": se, "z": (p - 0.5) / se, "band": band,
            "acf": acfs, "n_outside": sum(1 for v in acfs.values() if abs(v) > band),
            "runs_z": G.runs_z(s)}


def ruin(mid: np.ndarray, step: float, past: bool = False) -> list[dict]:
    """Non-overlapping symmetric-ish barrier replay on the lattice.

    `past=False` triggers when price reaches the level, `past=True` when it is
    strictly beyond it - `deriving.md` section three shows the two conventions
    give `S/(S+T)` and `(S+d)/(S+T+2d)` and that the second is what
    `generators.md`'s replay measured.
    """
    out = []
    lat = np.round(mid / step).astype(np.int64)
    for stop, tgt in ((5, 5), (5, 10), (5, 15), (10, 10), (5, 25)):
        i, hits, taus = 0, 0, []
        n = lat.size
        while i < n - 1:
            x0 = lat[i]
            j = i + 1
            res = 0
            while j < n:
                d = lat[j] - x0
                if (d > tgt) if past else (d >= tgt):
                    res = 1
                    break
                if (d < -stop) if past else (d <= -stop):
                    res = -1
                    break
                j += 1
            if res == 0:
                break
            hits += 1 if res > 0 else 0
            taus.append(j - i)
            i = j
        if len(taus) < 30:
            continue
        t = np.array(taus, dtype=float)
        d0 = 1.0
        out.append({"S": stop, "T": tgt, "n": len(taus), "p": hits / len(taus),
                    "p_theory": ((stop + d0) / (stop + tgt + 2 * d0) if past
                                 else stop / (stop + tgt)),
                    "se_p": math.sqrt(0.25 / len(taus)),
                    "etau": float(t.mean()), "etau_theory": float(stop * tgt),
                    "se_tau": float(t.std(ddof=1) / math.sqrt(t.size))})
    return out


def break_bars(bars: dict, step: float = 1.0) -> np.ndarray:
    """Bars whose range is larger than sixty unit steps can span.

    The cut is in *price*, so it has to carry the step size. `genrange.py` wrote
    it as a bare 66 because Range Break happens to step by exactly 1.0 in price;
    keeping the step explicit means the same function reads a rebuild quoted on
    any grid.
    """
    return (bars["high"] - bars["low"]) > BREAK_CUT * step


def vr_absolute(chg: np.ndarray, n: int, step: float, tpb: int = TPB) -> float:
    """`deriving.md` section four: `Var(C_{t+n} - C_t) / (n * tpb * d^2)`.

    1.0 is a free lattice walk of `tpb` unit steps a bar. Non-overlapping sums,
    so the standard error is `sqrt(2/k)` on `k = len(chg)//n` windows.
    """
    if chg.size < n * 20:
        return float("nan")
    agg = chg[: (chg.size // n) * n].reshape(-1, n).sum(axis=1)
    if agg.size < 10:
        return float("nan")
    return float(agg.var(ddof=0) / (n * tpb * step * step))


def vr_curves(bars: dict, step: float) -> dict:
    """Three readings, because the published table has to be reproduced before
    it can be used as a target.

    `all` is every bar. `splice` drops the break bars' own changes and sums what
    is left as if contiguous. `window` keeps only n-bar windows with no break in
    them. They are different estimators and only one of them can produce the
    published 0.279 at n=1000, since a thousand-minute window with no break has
    probability 1e-5.
    """
    cl = bars["close"]
    chg = np.diff(cl)
    brk = break_bars(bars, step)[1:]
    out = {"n_bars": int(cl.size), "n_breaks": int(brk.sum()),
           "bars_per_break": cl.size / max(int(brk.sum()), 1),
           "all": {}, "splice": {}, "window": {}, "se": {}}
    keep = chg[~brk]
    for n in VR_N:
        out["all"][n] = vr_absolute(chg, n, step)
        out["splice"][n] = vr_absolute(keep, n, step)
        out["se"][n] = math.sqrt(2.0 / max(chg.size // n, 1))
        # windows with no break: cumulative sums, sliding, break-free only
        if chg.size > n * 20:
            cs = np.concatenate([[0.0], np.cumsum(chg)])
            bc = np.concatenate([[0], np.cumsum(brk.astype(np.int64))])
            i = np.arange(0, chg.size - n)
            good = (bc[i + n] - bc[i]) == 0
            if good.sum() > 30:
                d = cs[i + n][good] - cs[i][good]
                out["window"][n] = float(d.var(ddof=0) / (n * TPB * step * step))
                out["window"][f"{n}_n"] = int(good.sum())
            else:
                out["window"][n] = float("nan")
                out["window"][f"{n}_n"] = int(good.sum())
    # the break's share of variance, deriving.md's other statement
    out["break_share"] = {}
    for n in (1, 200):
        a, s = out["all"].get(n), out["splice"].get(n)
        if a and s and not math.isnan(a) and not math.isnan(s):
            out["break_share"][n] = 1.0 - s / a
    return out


def break_stats(bars: dict, step: float) -> dict:
    brk = break_bars(bars, step)
    idx = np.flatnonzero(brk)
    gaps = np.diff(idx).astype(float)
    jump = np.abs(bars["close"][idx] - bars["open"][idx]) / step
    span = bars["n"]
    return {"n_breaks": int(idx.size), "minutes_per_break": span / max(idx.size, 1),
            "gap_cv": float(gaps.std(ddof=1) / gaps.mean()) if gaps.size > 2 else float("nan"),
            "gap_mean": float(gaps.mean()) if gaps.size else float("nan"),
            "jump_median": float(np.median(jump)) if jump.size else float("nan"),
            "jump_mean": float(jump.mean()) if jump.size else float("nan"),
            "jump_sd": float(jump.std(ddof=1)) if jump.size > 2 else float("nan"),
            "jump_q": {q: float(np.percentile(jump, q)) for q in (10, 50, 90, 99)}
            if jump.size else {},
            "_jump": jump, "_idx": idx}


def visited_ranges(bars: dict, step: float) -> np.ndarray:
    """max(high) - min(low) over each run of bars between two breaks, in steps.

    This is the statistic the band width is fitted on. It is not the variance
    ratio, and it is not the break rate, so the six variance ratios stay
    out-of-sample.
    """
    brk = break_bars(bars, step)
    idx = np.flatnonzero(brk)
    out = []
    for a, b in zip(idx, idx[1:], strict=False):
        if b - a < 5:
            continue
        out.append((bars["high"][a + 1:b].max() - bars["low"][a + 1:b].min()) / step)
    return np.array(out)


# ------------------------------------------------------------- simulation ----
def sim_step(n_bars: int, p_up: float, seed: int, p0: float) -> dict:
    rng = np.random.default_rng(seed)
    return G.bars_from_stream(G.gen_step(n_bars * TPB, STEP_SIZE, p_up, p0, rng),
                              TPB, n_bars, keep_ticks=min(n_bars * TPB, 200_000))


def sim_rb(n_bars: int, band: int, mean_break_ticks: float, jump_pool, seed: int,
           p0: float, step: float, anchor: str = "edge") -> dict:
    rng = np.random.default_rng(seed)
    return G.bars_from_stream(
        G.gen_rangebreak(n_bars * TPB, step, band, mean_break_ticks, 0.0, p0, rng,
                         jump_pool=jump_pool, anchor=anchor),
        TPB, n_bars, keep_ticks=min(n_bars * TPB, 200_000))


def fit_band(target: np.ndarray, mean_break_ticks: float, jump_pool, p0: float,
             step: float, seed: int, n_bars: int = 60_000,
             anchor: str = "edge") -> tuple[int, float, float]:
    """One parameter, fitted on the *visited* range and nothing else.

    Bisection to match the median, then a short scan around it minimising the
    two-sample KS distance between the simulated and the measured visited-range
    distributions. The median alone is not enough because that distribution has
    an atom at the band width - a walk that crosses its range before the break
    visits exactly the band - so a one-step error moves half the mass and the
    median cannot see it.

    Nothing about the variance-ratio curve enters here, which is what keeps that
    curve a prediction.
    """
    target_median = float(np.median(target))
    lo, hi = 8, 4000
    for _ in range(12):
        mid = (lo + hi) // 2
        v = visited_ranges(sim_rb(n_bars, mid, mean_break_ticks, jump_pool, seed, p0,
                                  step, anchor), step)
        got = float(np.median(v)) if v.size > 20 else float("nan")
        if math.isnan(got):
            break
        if got < target_median:
            lo = mid
        else:
            hi = mid
        if hi - lo <= 1:
            break
    base = (lo + hi) // 2
    best, best_d, best_med = base, float("inf"), float("nan")
    for band in range(max(8, base - 4), base + 5):
        v = visited_ranges(sim_rb(n_bars, band, mean_break_ticks, jump_pool, seed, p0,
                                  step, anchor), step)
        if v.size < 20:
            continue
        d = G.ks2(target, v)["D"]
        if d < best_d:
            best, best_d, best_med = band, d, float(np.median(v))
    return best, best_med, best_d


