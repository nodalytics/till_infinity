def two_barrier(logp: np.ndarray, a: float, b: float, u: float) -> dict:
    """`derivegbm.py`'s non-overlapping barrier replay, monitoring at the close."""
    n = logp.size
    i, ups = 0, 0
    taus = []
    while i < n - 1:
        x0 = logp[i]
        j = i + 1
        hit = 0
        while j < n:
            d = (logp[j] - x0) / u
            if d >= a:
                hit = 1
                break
            if d <= -b:
                hit = -1
                break
            j += 1
        if hit == 0:
            break
        ups += 1 if hit > 0 else 0
        taus.append(j - i)
        i = j
    if not taus:
        return {"n": 0}
    t = np.array(taus, dtype=float)
    return {"n": len(taus), "p_up": ups / len(taus), "etau": float(t.mean()),
            "se_p": math.sqrt(0.25 / len(taus))}


def tick_barrier(logp: np.ndarray, a: float, b: float, u: float,
                 cap: int = 3_000_000) -> tuple[float, int]:
    """The same non-overlapping barrier replay, monitored on every tick.

    A list is used rather than a numpy array because the scan is inherently
    sequential and Python list indexing is about three times faster than numpy
    scalar indexing; at three million ticks that is the difference between
    seconds and a minute.
    """
    x = (np.asarray(logp[:cap], dtype=float) / u).tolist()
    n = len(x)
    i, ups, taus = 0, 0, 0
    while i < n - 1:
        x0 = x[i]
        j = i + 1
        hit = 0
        while j < n:
            d = x[j] - x0
            if d >= a:
                hit = 1
                break
            if d <= -b:
                hit = -1
                break
            j += 1
        if hit == 0:
            break
        ups += 1 if hit > 0 else 0
        taus += 1
        i = j
    return (ups / taus if taus else float("nan")), taus


def battery(ts, _open, h, lo, cl, nominal, ticks=None, keep_rets=True) -> dict:
    r = G.logrets(cl, ts)
    got = {
        "n_bars": int(cl.size), "n_rets": int(r.size),
        "ann_vol": G.ann_vol(r), "ann_vol_se": G.ann_vol_se(r),
        "kurtosis": G.kurtosis(r), "kurtosis_se": G.kurtosis_se(r.size),
        "skew": float((((r - r.mean()) / r.std(ddof=0)) ** 3).mean()),
        "parkinson_ratio": G.parkinson_ratio(h, lo, cl),
        "acf_ret": {lg: G.acf(r, lg) for lg in G.LAGS},
        "acf_abs": {lg: G.acf(np.abs(r), lg) for lg in G.LAGS},
        "vr": {q: G.variance_ratio(r, q) for q in G.VR_Q},
        "vr_se": {q: G.variance_ratio_se(r, q) for q in G.VR_Q},
        # The sign sequence, tested the way `genstep.py` tests Step Index's: a
        # runs test catches alternation and persistence that a linear
        # autocorrelation on the returns themselves can miss.
        "sign_acf1": G.acf(np.sign(r), 1),
        "sign_band": 3.0 / math.sqrt(r.size),
        "runs_z": G.runs_z(np.sign(r)),
        "p_up": float((r > 0).mean()),
        "p_up_se": math.sqrt(0.25 / r.size),
        "mean_ret": float(r.mean()), "mean_ret_se": float(r.std(ddof=1) / math.sqrt(r.size)),
    }
    got["ratio_to_name"] = got["ann_vol"] / nominal
    got.update(G.hurst(ts, cl))
    u = (nominal / 100.0) / math.sqrt(G.MINUTES_PER_YEAR)
    # The barrier replay is a scan in Python, so it is capped at 300,000 bars -
    # 3.5x the real sample, which is already the sharper side of the comparison.
    lg = np.log(cl[:300_000])
    got["barrier"] = {f"{a}:{b}": two_barrier(lg, a, b, u) for a, b in PAIRS}
    if keep_rets:
        got["_rets"] = r
    if ticks is not None and ticks.size > 100:
        tr = np.diff(np.log(ticks))
        got["_tickrets"] = tr[np.isfinite(tr)]
    return got


def simulate_vol(feed, nominal, p0, grid, n_bars, seed, keep_ticks=0, sigma_mult=1.0,
                 student_df=0, tpb_override=0, cluster=False, lattice=LATTICE):
    tpb = tpb_override or ticks_per_bar(feed)
    # The seed is (run seed, feed) rather than the run seed alone. Seeding every
    # feed identically would hand all twelve rebuilds the same Gaussian draws
    # scaled by sigma, which makes the twelve comparisons one comparison and
    # produces byte-identical variance ratios down the column. That is the
    # dead-column failure in a new costume, and the first version of this
    # harness did it.
    rng = np.random.default_rng([int(seed), G.feed_seed(feed)])
    tick_s = 60.0 / tpb
    # `drop` is not a quantiser, it is an *observation* rule: the stream is the
    # price-rounded one - which is what the venue's own bars are built from - and
    # the repeated quotes are deleted from the ticks afterwards, which is what
    # our collector does. It therefore applies to the deliberately wrong
    # generators identically, and the over-collection is because the deletion
    # shortens the tick stream.
    dedup = lattice == "drop"
    mode = "price" if dedup else lattice
    want = int(keep_ticks * 1.6) if (dedup and keep_ticks) else keep_ticks
    if student_df:
        stream = _student_stream(n_bars * tpb, nominal * sigma_mult, tick_s, p0, grid,
                                 rng, student_df, lattice=mode)
    elif cluster:
        stream = _cluster_stream(n_bars * tpb, nominal * sigma_mult, tick_s, p0, grid,
                                 rng, tpb, lattice=mode)
    else:
        stream = G.gen_gbm(n_bars * tpb, nominal * sigma_mult, tick_s, p0, grid, rng,
                           lattice=mode)
    out = G.bars_from_stream(stream, tpb, n_bars, keep_ticks=want)
    if dedup and out["ticks"].size:
        tk = out["ticks"]
        out["ticks"] = tk[np.concatenate([[True], np.diff(tk) != 0])][:keep_ticks]
    return out


def _cluster_stream(n_ticks, sigma_ann, tick_seconds, p0, grid, rng, tpb,
                    block_bars=60, lo=0.7, hi=1.3, lattice=LATTICE):
    """The other deliberately wrong generator: the same average variance, but it
    alternates between two volatility states in hour-long blocks.

    This is what every real market does and no Deriv synthetic does
    (`generators.md`: largest |acf| of |return| across 26 synthetics is 0.017
    against gold's 0.219). It exists to prove the clustering test has power.
    """
    mode = G.lattice_mode(lattice)
    base = (sigma_ann / 100.0) * math.sqrt(tick_seconds / G.SECONDS_PER_YEAR)
    scale = base / math.sqrt((lo ** 2 + hi ** 2) / 2.0)
    blk = block_bars * tpb
    logp = math.log(p0)
    price = p0
    done = 0
    state = 0
    while done < n_ticks:
        m = min(blk, n_ticks - done)
        mult = lo if state == 0 else hi
        state = 1 - state
        path = logp + np.cumsum(rng.standard_normal(m) * scale * mult)
        logp = float(path[-1])
        px = np.exp(path)
        # the same quantiser as the honest rebuild: a control that differs in the
        # law *and* in the lattice rule cannot say which of the two was caught
        out = G.lattice_walk(px, price, grid, mode, scale * mult, rng)
        price = float(out[-1])
        yield out
        done += m


def _student_stream(n_ticks, sigma_ann, tick_seconds, p0, grid, rng, df, chunk=2_000_000,
                    lattice=LATTICE):
    """The deliberately wrong generator: Student-t tick innovations rescaled to
    the same per-tick variance. Same volatility, same martingale, wrong law."""
    mode = G.lattice_mode(lattice)
    sigma_tick = (sigma_ann / 100.0) * math.sqrt(tick_seconds / G.SECONDS_PER_YEAR)
    scale = sigma_tick / math.sqrt(df / (df - 2.0))
    logp = math.log(p0)
    price = p0
    done = 0
    while done < n_ticks:
        m = min(chunk, n_ticks - done)
        path = logp + np.cumsum(rng.standard_t(df, m) * scale)
        logp = float(path[-1])
        px = np.exp(path)
        out = G.lattice_walk(px, price, grid, mode, sigma_tick, rng)
        price = float(out[-1])
        yield out
        done += m


