"""Rebuild the Volatility and Jump families from the derived specification, then
try to tell the rebuild apart from the feed.

`deriving.md` says `volatility_N_index` is driftless geometric Brownian motion
whose annualised volatility is exactly `N` percent, annualising at 365*24*60,
published every two seconds (the plain family) or every second (the `_1s`
twins). That is **two numbers per instrument**. This harness takes only those
two numbers, simulates ticks, aggregates them into one-minute bars with the
feed's own rule, and then runs the identical battery `genvol.py`, `fractal.py`
and `derivegbm.py` ran on the real feed.

The Jump family is the same exercise with an ambiguity in it.
`generators.md` measured 1.322x the name on all five and read it as a
convention - the name is the *diffusive* volatility and the jumps are extra,
leaving `1.322^2 - 1 = 0.7477` of the diffusive variance for them. The other
reading is that the diffusion itself runs at 1.322x and the jumps sit on top.
Those are different generators and they predict different kurtosis, so both are
built and the data is allowed to choose.

## What would count as failure, written before any number was looked at

1. **The volatility spec fails** if a rebuilt feed's realised annualised
   volatility lands outside the **0.5%** band `genvol.py` established against
   the name - the same bar the real feeds cleared, on all twelve.
2. **The Gaussian claim fails** if rebuilt 1m kurtosis is outside `3.00 +- 3
   SE` (`SE = sqrt(24/n)`, which is 0.0167 on 86,410 bars) or the
   structure-function Hurst exponent is outside `0.50 +- 0.01`, where the real
   feeds read 2.98-3.02 and 0.50.
3. **The tick model fails** if the rebuilt Parkinson-to-close ratio misses the
   real feed's by more than **1%**. This is the sharpest test on the page,
   because 0.870 and 0.909 are *not inputs* - they are what 30 and 60 ticks a
   bar produce, and `deriving.md` derives them from the 0.5826 constant to
   0.30%. A rebuild that gets the law right and the tick rate wrong fails here
   and nowhere else.
4. **The distributional claim fails** if a two-sample KS on 1m log returns,
   real against rebuilt, rejects at alpha = 0.05 on more than **3 of the 12**
   feeds. Twelve comparisons at a 5% test are expected to reject 0.6 times;
   three is the 99th percentile of Binomial(12, 0.05) and is the line.
5. **The independence claim fails** if the 66 pairwise correlations among the
   rebuilt feeds do not look like the 66 among the real feeds - specifically if
   the largest rebuilt |corr| exceeds the largest real one by more than the
   0.0068 two-standard-error band, or if the leading eigenvalue of the 12x12
   correlation matrix separates real from rebuilt.
6. **The run is void** if a statistic lands on *exactly* its null - kurtosis
   3.000000, a variance ratio of 1.000000, a correlation of 0.000000. This
   folder has published a dead column twice and it is a bug to hunt, not a
   match.
7. **The run is void** if the positive controls do not fire. A generator with
   sigma set 1% wrong, and one with Student-t(6) returns at matched variance,
   are put through the identical battery. If the battery cannot see a
   deliberately wrong generator then it cannot certify a right one, and nothing
   below is evidence.


## Amended before the real data was touched, and why

Every harness here was first run end to end against a **synthetic** database -
sixty days of bars and twenty-four hours of ticks for all twenty-six feeds,
generated by these same generators - so that a crash or a broken test would
surface on data whose truth was known rather than on the lab. Three conditions
were rewritten during that dry run. Each amendment is recorded here rather than
quietly applied, because a failure condition edited after seeing the answer is
not a failure condition, and the only defence is to say exactly when it was
edited and what forced it.

* **The positive controls were widened from two to seven.** Student-t(6) at
  matched tick variance turned out to be nearly invisible in *bar* returns - a
  bar is thirty or sixty ticks and the central limit theorem gets there first -
  so each wrong generator is now scored across the whole battery and counted as
  caught if any test sees it. Two rungs were added that test claims nothing else
  does: **half the tick rate** at the same volatility, which only the Parkinson
  ratio can see, and a **two-state volatility** at the same average variance,
  which only the clustering test can see. The VOID condition still names the two
  generators it originally named.
* **A resolution ladder** (sigma +1%, +0.5%, +0.2%) was added and is explicitly
  *not* required to be caught. Its job is to say where the battery runs out.

## The tick-monitored barrier, predicted before it is measured

`deriving.md` section one's whole table is **close-monitored**: `derivegbm.py`
walks non-overlapping windows on one-minute closes, so `P(up) = (b+B)/(a+b+2B)`
and `E[tau] = (a+B)(b+B)` are the answers for a rule that can only act once a
minute. **A real stop is hit on a tick.** The correction scales as
`beta * sigma * sqrt(dt)`, so at `tpb` ticks a minute the shift in one-minute
sigmas falls from 0.5826 to `0.5826 / sqrt(tpb)` - **0.1064** at 30 ticks a bar
and **0.0752** at 60 - and the trading-relevant hit probability sits *between*
the continuous answer and the published one.

Written down before any of it was run, at a 3:1 stop-to-target:

| | continuous | close-monitored (published) | **tick-monitored (predicted)** |
| --- | --- | --- | --- |
| 3:1, 30 ticks a bar | 0.2500 | 0.3073 measured / 0.3064 derived | **0.2626** |
| 3:1, 60 ticks a bar | 0.2500 | 0.3073 / 0.3064 | **0.2591** |
| 1:3, 30 ticks a bar | 0.7500 | 0.6928 / 0.6936 | **0.7374** |
| 2:10, 30 ticks a bar | 0.8333 | 0.8042 / 0.8038 | **0.8275** |

That is a number this desk sizes on and does not have: a 1:3 barrier is a 25.0%
shot continuously, a 30.7% shot to a rule that checks once a minute, and a
**26.3%** shot to a stop that sits in the book. The published figure overstates
it by four points.

**It fails** if the measured tick-monitored `P(up)` is outside 0.005 of the
prediction on the rebuilt paths, or if the real tick table - 43,000 to 86,400
ticks a feed, about 400 non-overlapping 3:1 trades each, 5,000 pooled - puts it
more than 3 standard errors away. The gap between the close-monitored and
tick-monitored values is 0.045, which is 6.3 standard errors at that count, so
the sample resolves it; if it did not, that would be said instead.

## The controls

* **real against real** - the first thirty days against the last thirty, through
  the same tests. Whatever that produces is the floor; a rebuild that does no
  worse is indistinguishable in the only sense this sample can support.
* **sigma + 1%** and **Student-t(6)** as deliberately wrong generators.
* **across seeds** - every headline number is reported as a mean and a spread
  over `SEEDS` independent seeds, against the real feed's own standard error.
  A rebuild whose seed-to-seed spread is comparable to the real standard error
  has not been tested; the Monte Carlo has to be the sharper instrument.
"""

